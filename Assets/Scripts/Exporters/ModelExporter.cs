    /// <summary>
    /// The uma shader parameters an MMD material has no field for, written into the material comment as one
    /// line of key=value pairs. mmd_tools imports that comment onto the material
    /// (<c>material.mmd_material.comment</c>), and the uma addon's Shading operator reads it back to set its
    /// shader up with the values this model was exported with instead of its own defaults. Anything that does
    /// not know about it sees a comment, and a property the game renames is skipped rather than breaking the
    /// export - which is also how a rename will be noticed.
    ///
    /// Values use dots for decimals and commas only between the components of a colour, and the numbers are
    /// written with the invariant culture so that a machine with a comma decimal separator cannot produce a
    /// comment that parses as something else.
    /// </summary>
    private static string UmaMaterialComment(Material material, RawMMDModel model)
    {
        if (material == null) return "";

        var comment = new StringBuilder("uma1");
        void Number(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            comment.Append(' ').Append(key).Append('=')
                   .Append(material.GetFloat(property).ToString("0.####", CultureInfo.InvariantCulture));
        }
        void Tint(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            Color colour = material.GetColor(property);
            comment.Append(' ').Append(key).Append('=').Append(string.Join(",",
                colour.r.ToString("0.###", CultureInfo.InvariantCulture),
                colour.g.ToString("0.###", CultureInfo.InvariantCulture),
                colour.b.ToString("0.###", CultureInfo.InvariantCulture),
                colour.a.ToString("0.###", CultureInfo.InvariantCulture)));
        }
        void Vector(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            Vector4 value = material.GetVector(property);
            comment.Append(' ').Append(key).Append('=').Append(string.Join(",",
                value.x.ToString("0.####", CultureInfo.InvariantCulture),
                value.y.ToString("0.####", CultureInfo.InvariantCulture),
                value.z.ToString("0.####", CultureInfo.InvariantCulture),
                value.w.ToString("0.####", CultureInfo.InvariantCulture)));
        }
        void Map(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            var texture = material.GetTexture(property) as Texture2D;
            if (texture == null) return;
            comment.Append(' ').Append(key).Append('=').Append(texture.name);
        }

        // the shade ramp and the light threshold are what the Blender shader group calls "Shaded Texture"
        // and "Light Threshold"
        Number("toon_step", "_ToonStep");
        Number("toon_feather", "_ToonFeather");
        Number("specular_power", "_SpecularPower");
        Tint("specular", "_SpecularColor");
        Number("env_rate", "_EnvRate");
        Number("env_bias", "_EnvBias");
        Number("rim_step", "_RimStep");
        Number("rim_feather", "_RimFeather");
        Tint("rim", "_RimColor");
        Number("rim_spec_rate", "_RimSpecRate");
        Number("rim_shadow", "_RimShadow");
        Number("outline_width", "_OutlineWidth");
        Tint("outline", "_OutlineColor");
        Tint("chara", "_CharaColor");
        Number("saturation", "_Saturation");
        Tint("toon_bright", "_ToonBrightColor");
        Tint("toon_dark", "_ToonDarkColor");
        Number("emissive_intensity", "_EmissiveIntensity");
        Number("emissive_rim_power", "_EmissiveRimPower");
        Number("emissive_rim_intensity", "_EmissiveRimIntensity");
        Number("use_option_mask", "_UseOptionMaskMap");

        // what the game's face shader needs and an MMD material has no field for. _faceShadow* gates the cheek and
        // nose regions, so without them the addon cannot tell a character whose regions are on from one whose are
        // off; _NormalizeNormal 0 means the game uses the raw vertex normal rather than a normalised one.
        //
        // _CylinderBlend comes from the material, and after this round it is the *shipped asset's* value rather
        // than an override: the game sets the rim, toon and saturation values at runtime
        // (Gallop/Live/Director.cs:215-258) and never sets this one, so the asset's value is what the game
        // renders with. The viewer used to force 0.25 here, which the exporter then carried; that override is
        // gone. The cost of the change was measured at 0.04 of a level on the face crop's mean luminance.
        Number("cylinder_blend", "_CylinderBlend");
        Number("normalize_normal", "_NormalizeNormal");
        Number("face_shadow_end_y", "_faceShadowEndY");
        Number("face_shadow_length", "_faceShadowLength");
        // the alpha that gates the region path. In the game it is *driven*: Gallop/FaceDrivenKeyTarget binds it,
        // with no curve between them, to the X scale of a locator named "Shade_Ctrl" (BindProperty.LocatorPart.ScaX,
        // Type Shader, PropertyName "_faceShadowAlpha"). That locator is neither a bone nor a morph in the exported
        // skeleton - the export has no node by that name at all - so what a static pmx can carry is the rest value.
        // Writing it means a character whose material does set the alpha renders its regions with nobody forcing it.
        Number("face_shadow_alpha", "_faceShadowAlpha");
        Tint("face_shadow_color", "_faceShadowColor");
        // the two strengths the region gates compare `factor >= 1 - strength` against: named for exactly
        // that role, and 0.775 makes a threshold the factor can actually cross
        Number("cheek_threshold", "_CheekPretenseThreshold");
        Number("nose_threshold", "_NosePretenseThreshold");
        Number("vertex_color_toon_power", "_VertexColorToonPower");
        Vector("original_light", "_OriginalDirectionalLightDir");

        // The region colours, and they are per character: the viewer sets all twelve from the character's own
        // colour data rows at runtime (UmaContainerCharacter.SetMaskColor), so an export that omits them leaves the
        // region path with nothing to switch between. Six for the surface and six for the toon side, R/G/B in
        // pairs, matching the six colour constants the game's pixel program uses.
        // (The region's own gate, _faceShadowAlpha, is written above with the other face-shader values. It is a
        // *driven* property of the facial driven-key system - Gallop/FaceDrivenKeyTarget binds it to the X scale
        // of a locator named "Shade_Ctrl" - so what the export can carry is its rest value. See the note there.)
        Tint("mask_r1", "_MaskColorR1");
        Tint("mask_r2", "_MaskColorR2");
        Tint("mask_g1", "_MaskColorG1");
        Tint("mask_g2", "_MaskColorG2");
        Tint("mask_b1", "_MaskColorB1");
        Tint("mask_b2", "_MaskColorB2");
        Tint("mask_toon_r1", "_MaskToonColorR1");
        Tint("mask_toon_r2", "_MaskToonColorR2");
        Tint("mask_toon_g1", "_MaskToonColorG1");
        Tint("mask_toon_g2", "_MaskToonColorG2");
        Tint("mask_toon_b1", "_MaskToonColorB1");
        Tint("mask_toon_b2", "_MaskToonColorB2");

        // the maps an MMD material has no field for, by name so the addon does not have to guess file names
        Map("triple", "_TripleMaskMap");
        Map("option", "_OptionMaskMap");
        Map("toon", "_ToonMap");
        Map("env", "_EnvMap");
        Map("emissive", "_EmissiveTex");
        return comment.ToString();
    }

    /// <summary>
    /// The extra facial morphs that touch a material, as one <c>morph=</c> token in its comment.
    ///
    /// An MMD material has no slot for a texture swap or a shader property, but it does have a comment, and the
    /// uma addon reads it back (<c>material.mmd_material.comment</c>). The grammar is one token per material,
    /// holding every morph that binds it: <c>morph=&lt;morph&gt;:&lt;bind type&gt;:&lt;locator part&gt;:&lt;property&gt;[, ...]</c>,
    /// so the cheek decal reads <c>morph=Cheek_Ctrl:Texture:ScaX:_CheekRate,ScaY:_CheekRate,ScaZ:_CheekRate</c>.
    /// The locator part is the axis of the transform the game's own animation drives; turning that into a
    /// driver is the addon's job. Anything that does not know the token sees a comment.
    /// </summary>
    private static string ExtraMorphComment(UmaContainerCharacter character, Material material)
    {
        if (character == null || material == null) return string.Empty;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return string.Empty;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return string.Empty;

        string target = material.name.Replace(" (Instance)", "");
        var morphs = new StringBuilder();
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            var bindings = new StringBuilder();
            string type = null;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null || property.BindMaterial == null) continue;
                if (property.Type != BindProperty.BindType.Texture && property.Type != BindProperty.BindType.Shader)
                    continue;
                if (property.BindMaterial.name.Replace(" (Instance)", "") != target) continue;
                bindings.Append(bindings.Length > 0 ? "," : "").Append(property.Part).Append(':')
                        .Append(property.PropertyName);
                type = property.Type.ToString();
            }
            if (bindings.Length == 0) continue;
            morphs.Append(morphs.Length > 0 ? ";" : "").Append(LocatorName(morph)).Append(':').Append(type)
                  .Append(':').Append(bindings);
        }
        return morphs.Length == 0 ? string.Empty : " morph=" + morphs;
    }

    /// <summary>
    /// The sprite-sheet grid of an animated tear material, as `scroll=<cols>x<rows>`.
    ///
    /// The scroll itself is the `_scrN` UV morphs; this token says what grid those morphs step through, so a
    /// consumer that cannot play UV morphs (the Blender addon) can move the texture itself by the same grid.
    /// The grid is the prefab's, not the material's: `texture_width`/`_height` and the part size come from the
    /// tear object's own asset table.
    /// </summary>
    private static string ExtraMorphGrid(UmaContainerCharacter character, Renderer renderer)
    {
        if (character == null || renderer == null || character.TearControllers == null) return string.Empty;
        foreach (TearController tear in character.TearControllers)
        {
            if (tear == null) continue;
            foreach (GameObject tearObject in new GameObject[] { tear.TearObject_0, tear.TearObject_1 })
            {
                if (tearObject == null) continue;
                if (!renderer.transform.IsChildOf(tearObject.transform)) continue;
                AssetHolder holder = tearObject.GetComponent<AssetHolder>();
                if (holder == null || holder._assetTableValue == null) continue;
                float width = holder._assetTableValue["texture_width"];
                float height = holder._assetTableValue["texture_height"];
                float partWidth = holder._assetTableValue["texture_part_width"];
                float partHeight = holder._assetTableValue["texture_part_height"];
                if (width <= 0f || height <= 0f || partWidth <= 0f || partHeight <= 0f) continue;
                int columns = Mathf.Max(1, Mathf.RoundToInt(width / partWidth));
                int rows = Mathf.Max(1, Mathf.RoundToInt(height / partHeight));
                if (columns * rows <= 1) continue;
                // `roll=` is how long one pass of the card's own animation takes, followed by the normalised
                // times its roll morphs were sampled at, so a consumer can time the stack without the clip. It
                // is absent for a card the clip does not move.
                string roll = string.Empty;
                foreach (Renderer tearRenderer in tearObject.GetComponentsInChildren<Renderer>(true))
                {
                    if (tearRenderer != null && _tearRollPoses.ContainsKey(tearRenderer) && _tearRollLength > 0f)
                    {
                        var times = new List<string>();
                        foreach (float time in TearRollTimes)
                        {
                            times.Add(time.ToString("0.###", CultureInfo.InvariantCulture));
                        }
                        roll = " roll=" + _tearRollLength.ToString("0.###", CultureInfo.InvariantCulture)
                               + ":" + string.Join(",", times);
                        break;
                    }
                }
                return " scroll=" + columns + "x" + rows + roll;
            }
        }
        return string.Empty;
    }

    /// <summary>
    /// How the part is meant to be drawn, when MMD's plain alpha blend is not it.
    ///
    /// The cheek decal is a *multiply* overlay: its texture is white where the face shows through and tinted
    /// where the blush is, and the game's `MultiplyCheek` shader multiplies it into the face. An MMD material
    /// has no multiply blend, so exported as it is the decal paints a white shell over the cheeks. The token
    /// says what the part is, so a consumer that understands it - the uma addon - can multiply it instead;
    /// plain MMD still draws the texture with its own alpha, which is why the part is hidden by geometry at
    /// rest rather than by zeroing the material.
    /// </summary>
    private static string ExtraMorphBlend(Material material)
    {
        if (material == null || material.shader == null) return string.Empty;
        string shader = material.shader.name ?? string.Empty;
        if (shader.IndexOf("Multiply", System.StringComparison.OrdinalIgnoreCase) >= 0) return " blend=multiply";
        return string.Empty;
    }

    /// <summary>
    /// One vertex morph per decal part, carrying the offsets that put the part back where the game has it.
    ///
    /// Named for what a user looks for: `@_@_L` … `o_o_R` for the eye manga, `Tear_L`/`Tear_R` for the
    /// static tears, `Blush` for the blush decal. At weight 0 the part is collapsed away (the model's rest
    /// state, as in the game); at 1 it is deployed.
    /// </summary>
    private static List<Morph> DeployMorphs(UmaContainerCharacter character,
                                            List<(Renderer renderer, int start, int count)> ranges,
                                            HashSet<Renderer> restInvisible,
                                            Dictionary<int, Vector3> deployed,
                                            Vector3 collapsePoint)
    {
        var morphs = new List<Morph>();
        if (character == null) return morphs;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return morphs;

        var rangeOf = new Dictionary<Renderer, (int start, int count)>();
        foreach (var range in ranges) rangeOf[range.renderer] = (range.start, range.count);

        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null) continue;

            // the object the material lives on (the cheek decal) and the objects a bind shows and hides. By
            // *instance*, not by name: the four eye-manga prefabs are the same four names once for each eye,
            // so keying on the name folded the right eye into the left one and five parts came out where
            // eight belong.
            var parts = new List<GameObject>();
            if (morph.BindGameObject != null) parts.Add(morph.BindGameObject);
            if (morph.BindProperties != null)
            {
                foreach (BindProperty property in morph.BindProperties)
                {
                    if (property == null || property.BindPrefabs == null) continue;
                    foreach (GameObject prefab in property.BindPrefabs)
                    {
                        if (prefab == null || parts.Contains(prefab)) continue;
                        parts.Add(prefab);
                    }
                }
            }

            foreach (GameObject part in parts)
            {
                var data = new List<Morph.MorphData>();
                foreach (Renderer renderer in part.GetComponentsInChildren<Renderer>(true))
                {
                    if (renderer == null || !restInvisible.Contains(renderer)) continue;
                    if (!rangeOf.TryGetValue(renderer, out var range)) continue;
                    for (int i = range.start; i < range.start + range.count; i++)
                    {
                        if (!deployed.TryGetValue(i, out Vector3 where)) continue;
                        data.Add(new Morph.VertexMorphData
                        {
                            VertexIndex = i,
                            Offset = where - collapsePoint
                        });
                    }
                }
                if (data.Count == 0) continue;
                // where the part actually sits, from the vertices a deploy morph puts back - a mirrored
                // right-eye instance keeps the left one's position (the mirror is a negative scale), so the
                // renderer's own bounds cannot say which eye it is, while its deployed vertices can
                var sum = Vector3.zero;
                int placed = 0;
                foreach (var item in data)
                {
                    var vertex = (Morph.VertexMorphData)item;
                    if (!deployed.TryGetValue(vertex.VertexIndex, out Vector3 where)) continue;
                    sum += where;
                    placed++;
                }
                Vector3 centre = placed > 0 ? sum / placed : part.transform.position;
                string name = DeployName(character, part, centre);
                morphs.Add(new Morph
                {
                    Name = name,
                    NameEn = name,
                    Category = Morph.MorphCategory.MorphCatOther,
                    Type = Morph.MorphType.MorphTypeVertex,
                    MorphDatas = data.ToArray()
                });
            }
        }
        return morphs;
    }

    /// <summary>
    /// How far a deployed decal is lifted off the surface it was painted on, as a fraction of its distance from
    /// the head bone - 2% of the radius, a couple of millimetres on a real head. A fraction rather than an
    /// absolute length because the export is not in one unit system: the same decal is a few units from the head
    /// bone in file space and a few centimetres in the viewer's, and only the ratio means the same thing in both.
    /// </summary>
    private const float DecalLift = 0.06f;

    /// <summary>How many UV steps one full spin is divided into. Seven morphs plus the rest state make eight,
    /// so each step is 45 degrees and a cross-fade between two neighbours lands any rotation in between.</summary>
    private const int SpinSteps = 8;

    /// <summary>
    /// The UV morphs that make the dizzy face dizzy: the `@_@` decal's texture rotates, and no vertex moves.
    ///
    /// Each morph is one step of the turn (a rotation of the quad's own UVs about their centre), so the parts
    /// of a spin are the same picture rotated. A continuous spin is an animation that cross-fades consecutive
    /// morphs - linear weights over a linear UV delta add up to a linear rotation, so `w_k` falling while
    /// `w_{k+1}` rises is exactly the turn between them, with no easing to fake. The rest state is the decal
    /// at weight 0 everywhere, which is the orientation the game draws it in.
    /// </summary>
    /// <summary>
    /// The animated tears: one deploy morph per tear object, plus the scroll that makes them run.
    ///
    /// Each `TearController` keeps two prefabs (`pfb_chr_tear000`, `pfb_chr_tear001`) whose animation is a
    /// *sprite sheet scroll*: `TearController.UpdateOffset` steps `_TexScrollParam` across the sheet, and the
    /// grid comes from the prefab's own asset table (`texture_width`/`_height`, `texture_part_width`/`_height`).
    /// MMD has no texture offset, so the same roll is a stack of UV morphs - one per sheet frame, each
    /// translating every UV by that frame's step - exactly as the eye manga's turn is a stack of rotations.
    /// Frame 0 is the rest state, so a running tear is the deploy morph at 1 with the scroll morphs cycled
    /// through.
    /// </summary>
    private static List<Morph> TearMorphs(UmaContainerCharacter character,
                                          List<(Renderer renderer, int start, int count)> ranges,
                                          HashSet<Renderer> restInvisible,
                                          Dictionary<int, Vector3> deployed,
                                          Vector3 collapsePoint)
    {
        var morphs = new List<Morph>();
        if (character == null || character.TearControllers == null) return morphs;

        var rangeOf = new Dictionary<Renderer, (int start, int count)>();
        foreach (var range in ranges) rangeOf[range.renderer] = (range.start, range.count);

        for (int i = 0; i < character.TearControllers.Count; i++)
        {
            TearController tear = character.TearControllers[i];
            if (tear == null) continue;
            for (int variant = 0; variant < 2; variant++)
            {
                GameObject part = variant == 0 ? tear.TearObject_0 : tear.TearObject_1;
                AssetHolder holder = part.GetComponent<AssetHolder>();
                if (part == null) continue;

                var indices = new List<int>();
                Vector3 sum = Vector3.zero;
                int placed = 0;
                foreach (Renderer renderer in part.GetComponentsInChildren<Renderer>(true))
                {
                    if (renderer == null || !restInvisible.Contains(renderer)) continue;
                    if (!rangeOf.TryGetValue(renderer, out var range)) continue;
                    for (int v = range.start; v < range.start + range.count; v++)
                    {
                        if (!deployed.ContainsKey(v)) continue;
                        indices.Add(v);
                        sum += deployed[v];
                        placed++;
                    }
                }
                if (indices.Count == 0) continue;
                Vector3 centre = placed > 0 ? sum / placed : part.transform.position;
                string name = "TearDrop" + (i + 1) + (variant == 0 ? "" : "b") + "_" + SideOf(character, centre);

                var data = new List<Morph.MorphData>();
                foreach (int v in indices)
                {
                    data.Add(new Morph.VertexMorphData { VertexIndex = v, Offset = deployed[v] - collapsePoint });
                }
                morphs.Add(new Morph
                {
                    Name = name,
                    NameEn = name,
                    Category = Morph.MorphCategory.MorphCatOther,
                    Type = Morph.MorphType.MorphTypeVertex,
                    MorphDatas = data.ToArray()
                });
                morphs.AddRange(ScrollMorphs(name, indices, holder));
            }
        }
        return morphs;
    }

    /// <summary>The poses sampled for the tear roll, per renderer, in world space, and the clip's length in seconds.</summary>
    private static readonly Dictionary<Renderer, List<Vector3[]>> _tearRollPoses =
        new Dictionary<Renderer, List<Vector3[]>>();
    private static float _tearRollLength;

    /// <summary>
    /// Which points of the tear loop are stored as morphs, as normalised times into the clip.
    ///
    /// Sampled from the shipped animation, the card stands at the eye corner until about t=0.2, is clear of the
    /// eye and running down by t=0.5, and is at the chin and nearly gone by t=0.9. Three poses carry that
    /// motion: the addon cross-fades the weights between them, and a cross-fade between two stored poses is a
    /// straight interpolation, which is all a pmx morph can express anyway.
    /// </summary>
    private static readonly float[] TearRollTimes = { 0.2f, 0.5f, 0.9f };

    /// <summary>
    /// How far a card has to move, in world units, before it counts as animated. The tall card travels about 0.12;
    /// the wide one comes back within 0.002 of its own pose at every sample, which is noise rather than motion.
    /// </summary>
    private const float TearRollMinimumMoved = 0.01f;

    /// <summary>
    /// Samples the animated tear cards.
    ///
    /// The cards are skinned meshes posed by an Animator, so `mesh.vertices` - what the rest of this exporter
    /// reads - is only the bind pose: a stub standing at the eye corner. Two things are needed to see the real
    /// pose, and both cost a day to find the first time: the animator must be set to `AlwaysAnimate` (in the
    /// default culling mode it does not even write its bone transforms while the renderer is not being drawn,
    /// which in a headless run is always), and the object must be active. `BakeMesh` then runs the skinning for
    /// real. Only the tall `tear000` card animates; the wide `tear001` one is static, so its poses come back
    /// unchanged and it gets no roll morphs.
    /// </summary>
    private static void SampleTearRolls(UmaContainerCharacter character,
                                        List<(Renderer renderer, int start, int count)> ranges)
    {
        _tearRollPoses.Clear();
        _tearRollLength = 0f;
        if (character == null || character.TearControllers == null) return;

        var rangeOf = new Dictionary<Renderer, (int start, int count)>();
        foreach (var range in ranges) rangeOf[range.renderer] = (range.start, range.count);

        foreach (TearController tear in character.TearControllers)
        {
            if (tear == null) continue;
            foreach (GameObject part in new GameObject[] { tear.TearObject_0, tear.TearObject_1 })
            {
                if (part == null) continue;
                Animator animator = part.GetComponent<Animator>();
                if (animator == null || animator.runtimeAnimatorController == null) continue;

                AnimationClip[] clips = animator.runtimeAnimatorController.animationClips;
                AnimationClip clip = null;
                foreach (AnimationClip candidate in clips)
                {
                    if (candidate != null) { clip = candidate; break; }
                }
                if (clip == null || clip.length <= 0f) continue;

                bool wasActive = part.activeSelf;
                AnimatorCullingMode culling = animator.cullingMode;
                float speed = animator.speed;
                part.SetActive(true);
                try
                {
                    animator.cullingMode = AnimatorCullingMode.AlwaysAnimate;
                    animator.enabled = true;
                    animator.speed = 0f; // Play() sets the time; speed would let it drift between samples

                    foreach (SkinnedMeshRenderer renderer in part.GetComponentsInChildren<SkinnedMeshRenderer>(true))
                    {
                        if (renderer == null || !rangeOf.ContainsKey(renderer)) continue;
                        var poses = new List<Vector3[]>();
                        foreach (float time in TearRollTimes)
                        {
                            animator.Play(0, 0, time);
                            animator.Update(0.0001f);
                            var baked = new Mesh();
                            try
                            {
                                renderer.BakeMesh(baked, false);
                                Vector3[] vertices = baked.vertices;
                                var world = new Vector3[vertices.Length];
                                for (int i = 0; i < vertices.Length; i++)
                                {
                                    world[i] = renderer.transform.TransformPoint(vertices[i]);
                                }
                                poses.Add(world);
                            }
                            finally
                            {
                                UnityEngine.Object.DestroyImmediate(baked);
                            }
                        }
                        if (poses.Count == TearRollTimes.Length)
                        {
                            // the wide tear001 card does not animate, and returns the same pose three times
                            // give or take a sub-millimetre of noise. Below this threshold it is not a roll, and
                            // writing it would put a wall of near-zero morphs in the file and a bogus `roll=`
                            // token on its material.
                            float moved = 0f;
                            for (int step = 1; step < poses.Count; step++)
                            {
                                for (int v = 0; v < poses[step].Length && v < poses[0].Length; v++)
                                {
                                    moved = Mathf.Max(moved, (poses[step][v] - poses[0][v]).magnitude);
                                }
                            }
                            if (moved < TearRollMinimumMoved)
                            {
                                Debug.Log($"[export] '{part.name}' does not animate the card "
                                          + $"({moved:F4} world units over the clip), no roll morphs");
                                continue;
                            }
                            _tearRollPoses[renderer] = poses;
                            _tearRollLength = clip.length;
                        }
                    }
                }
                catch (Exception exception)
                {
                    Debug.Log($"[export] tear roll sampling failed on '{part.name}': {exception.GetType().Name}: "
                              + exception.Message);
                }
                finally
                {
                    animator.Play(0, 0, 0f);
                    animator.speed = speed;
                    animator.cullingMode = culling;
                    part.SetActive(wasActive);
                }
            }
        }
        if (_tearRollPoses.Count > 0)
        {
            Debug.Log($"[export] sampled {_tearRollPoses.Count} tear card(s) over a {_tearRollLength:F3}s loop, "
                      + $"{TearRollTimes.Length} poses each");
        }
    }

    /// <summary>
    /// The tear roll as a stack of vertex morphs, one per sampled pose, each offset measured from the pose the
    /// deploy morph produces. Deploy at 1 plus `_rollN` at 1 is the sampled pose, so the addon animates the card
    /// by cross-fading the roll weights - the same shape of trick as the `_scr` uv stack, one layer down.
    /// </summary>
    private static List<Morph> TearRollMorphs(UmaContainerCharacter character,
                                              List<(Renderer renderer, int start, int count)> ranges,
                                              HashSet<Renderer> restInvisible,
                                              Dictionary<int, Vector3> bindWorld)
    {
        var morphs = new List<Morph>();
        if (character == null || _tearRollPoses.Count == 0) return morphs;

        var rangeOf = new Dictionary<Renderer, (int start, int count)>();
        foreach (var range in ranges) rangeOf[range.renderer] = (range.start, range.count);

        for (int i = 0; i < character.TearControllers.Count; i++)
        {
            TearController tear = character.TearControllers[i];
            if (tear == null) continue;
            for (int variant = 0; variant < 2; variant++)
            {
                GameObject part = variant == 0 ? tear.TearObject_0 : tear.TearObject_1;
                if (part == null) continue;

                var indices = new List<int>();
                var renderers = new List<Renderer>();
                Vector3 sum = Vector3.zero;
                foreach (Renderer renderer in part.GetComponentsInChildren<Renderer>(true))
                {
                    if (renderer == null || !restInvisible.Contains(renderer)) continue;
                    if (!rangeOf.TryGetValue(renderer, out var range)) continue;
                    if (!_tearRollPoses.ContainsKey(renderer)) continue;
                    renderers.Add(renderer);
                    for (int v = range.start; v < range.start + range.count; v++)
                    {
                        if (!bindWorld.ContainsKey(v)) continue;
                        indices.Add(v);
                        sum += bindWorld[v];
                    }
                }
                if (indices.Count == 0) continue;
                Vector3 centre = sum / indices.Count;
                string name = "TearDrop" + (i + 1) + (variant == 0 ? "" : "b") + "_" + SideOf(character, centre);

                for (int step = 0; step < TearRollTimes.Length; step++)
                {
                    var data = new List<Morph.MorphData>();
                    foreach (Renderer renderer in renderers)
                    {
                        var range = rangeOf[renderer];
                        Vector3[] pose = _tearRollPoses[renderer][step];
                        for (int v = range.start; v < range.start + range.count; v++)
                        {
                            int local = v - range.start;
                            if (local < 0 || local >= pose.Length) continue;
                            if (!bindWorld.TryGetValue(v, out Vector3 bind)) continue;
                            Vector3 offset = pose[local] - bind;
                            // a card the clip does not move contributes nothing; skipping those vertices keeps
                            // the morph out of the file entirely rather than writing a wall of zeros
                            if (offset.sqrMagnitude < 1e-10f) continue;
                            data.Add(new Morph.VertexMorphData { VertexIndex = v, Offset = offset });
                        }
                    }
                    if (data.Count == 0) continue;
                    string rollName = name + "_roll" + (step + 1);
                    morphs.Add(new Morph
                    {
                        Name = rollName,
                        NameEn = rollName,
                        Category = Morph.MorphCategory.MorphCatOther,
                        Type = Morph.MorphType.MorphTypeVertex,
                        MorphDatas = data.ToArray()
                    });
                }
            }
        }
        return morphs;
    }

    /// <summary>The UV morph stack that rolls a tear through its sprite sheet, or none when the grid is unknown.</summary>
    private static List<Morph> ScrollMorphs(string name, List<int> indices, AssetHolder holder)
    {
        var morphs = new List<Morph>();
        if (holder == null || holder._assetTableValue == null) return morphs;
        float width = holder._assetTableValue["texture_width"];
        float height = holder._assetTableValue["texture_height"];
        float partWidth = holder._assetTableValue["texture_part_width"];
        float partHeight = holder._assetTableValue["texture_part_height"];
        if (width <= 0f || height <= 0f || partWidth <= 0f || partHeight <= 0f) return morphs;
        int columns = Mathf.Max(1, Mathf.RoundToInt(width / partWidth));
        int rows = Mathf.Max(1, Mathf.RoundToInt(height / partHeight));
        int frames = columns * rows;
        if (frames <= 1) return morphs;

        // one morph per sheet frame (frame 0 is the rest state), capped: an 8x4 sheet is 32 frames and 32 morphs
        // per tear object would swamp the list, so the stack is spread evenly over the sheet instead
        const int MaxSteps = 8;
        int stride = Mathf.Max(1, Mathf.CeilToInt((frames - 1) / (float)MaxSteps));
        for (int frame = stride; frame < frames; frame += stride)
        {
            float u = (frame % columns) / (float)columns;
            float v = (frame / columns) / (float)rows;
            var data = new List<Morph.MorphData>();
            foreach (int index in indices)
            {
                // The game steps the sheet with a *negative* y (`_TexScrollParam = (x, -offsetY)`) and this used
                // to write that same sign here. It is the wrong sign for the pmx, and the reason is the flip the
                // rest of the export does: uvs are written `1 - v` because the pmx stores v top-down, and
                // mmd_tools flips it back on import - but it *negates* a uv-morph offset's v as well
                // (`pmx.importer: (x, -y, z, -w)` rather than a flip), so the game's -v step has to be stored
                // as +v. Written as -v the stack walked the uvs off the sheet instead of through it: the base
                // cell is v [0, 1/rows], so seven steps of 1/rows reach exactly 1.0 stored the right way round
                // and -0.875 the wrong way.
                data.Add(new Morph.UvMorphData
                {
                    VertexIndex = index,
                    Offset = new Vector4(u, v, 0f, 0f)
                });
            }
            string stepName = name + "_scr" + morphs.Count;
            morphs.Add(new Morph
            {
                Name = stepName,
                NameEn = stepName,
                Category = Morph.MorphCategory.MorphCatOther,
                Type = Morph.MorphType.MorphTypeUv,
                MorphDatas = data.ToArray()
            });
        }
        return morphs;
    }

    private static List<Morph> SpinMorphs(UmaContainerCharacter character, RawMMDModel model,
                                          List<(Renderer renderer, int start, int count)> ranges,
                                          HashSet<Renderer> restInvisible,
                                          Dictionary<int, Vector3> deployed)
    {
        var morphs = new List<Morph>();
        if (character == null) return morphs;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return morphs;

        var rangeOf = new Dictionary<Renderer, (int start, int count)>();
        foreach (var range in ranges) rangeOf[range.renderer] = (range.start, range.count);

        // only the `@_@` face spins - the others are still pictures
        string spinFace = MangaFaces[0];
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            var parts = new List<GameObject>();
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null || property.BindPrefabs == null) continue;
                foreach (GameObject prefab in property.BindPrefabs)
                {
                    if (prefab == null || parts.Contains(prefab)) continue;
                    if (prefab.name.IndexOf("emo_eye_000", System.StringComparison.OrdinalIgnoreCase) < 0) continue;
                    parts.Add(prefab);
                }
            }

            foreach (GameObject part in parts)
            {
                var indices = new List<int>();
                var centre = Vector3.zero;
                int placed = 0;
                foreach (Renderer renderer in part.GetComponentsInChildren<Renderer>(true))
                {
                    if (renderer == null || !restInvisible.Contains(renderer)) continue;
                    if (!rangeOf.TryGetValue(renderer, out var range)) continue;
                    for (int i = range.start; i < range.start + range.count; i++)
                    {
                        indices.Add(i);
                        if (!deployed.TryGetValue(i, out Vector3 where)) continue;
                        centre += where;
                        placed++;
                    }
                }
                if (indices.Count < 3) continue;
                centre = placed > 0 ? centre / placed : Vector3.zero;

                var uv = new Vector2[indices.Count];
                Vector2 pivot = Vector2.zero;
                for (int i = 0; i < indices.Count; i++)
                {
                    uv[i] = model.Vertices[indices[i]].UvCoordinate;
                    pivot += uv[i];
                }
                pivot /= uv.Length;

                string name = spinFace + "_" + SideOf(character, centre);
                for (int step = 1; step < SpinSteps; step++)
                {
                    float angle = Mathf.PI * 2f * step / SpinSteps;
                    float cos = Mathf.Cos(angle), sin = Mathf.Sin(angle);
                    var data = new List<Morph.MorphData>();
                    for (int i = 0; i < indices.Count; i++)
                    {
                        Vector2 from = uv[i] - pivot;
                        Vector2 to = new Vector2(from.x * cos - from.y * sin, from.x * sin + from.y * cos);
                        Vector2 delta = to - from;
                        if (delta.sqrMagnitude < 1e-12f) continue;
                        data.Add(new Morph.UvMorphData
                        {
                            VertexIndex = indices[i],
                            Offset = new Vector4(delta.x, delta.y, 0f, 0f)
                        });
                    }
                    if (data.Count == 0) continue;
                    string morphName = name + "_spin" + step;
                    morphs.Add(new Morph
                    {
                        Name = morphName,
                        NameEn = morphName,
                        Category = Morph.MorphCategory.MorphCatOther,
                        Type = Morph.MorphType.MorphTypeUv,
                        MorphDatas = data.ToArray()
                    });
                }
            }
        }
        return morphs;
    }

    /// <summary>
    /// The expressions the four eye manga draw, in the order the game selects them. The names are the faces
    /// themselves - a `@_@` eye, a sparkle, a squint, a wide-open one - so a morph list reads like the emoticon
    /// it produces instead of like an index.
    /// </summary>
    private static readonly string[] MangaFaces = { "@_@", "✦_✦", ">_<", "o_o" };

    /// <summary>The morph name a decal part is shown under: `@_@_L`, `Tear_L`, `Blush`.</summary>
    private static string DeployName(UmaContainerCharacter character, GameObject part, Vector3 centre)
    {
        string name = (part != null ? part.name : string.Empty)
            .Replace(" (Clone)", "").Replace("(Clone)", "");
        int eye = name.IndexOf("emo_eye_", System.StringComparison.OrdinalIgnoreCase);
        if (eye >= 0)
        {
            string suffix = name.Substring(eye + "emo_eye_".Length);
            string face = "Manga";
            if (suffix.Length >= 3 && int.TryParse(suffix.Substring(suffix.Length - 3), out int index)
                && index >= 0 && index < MangaFaces.Length)
            {
                face = MangaFaces[index];
            }
            return face + "_" + SideOf(character, centre);
        }
        if (name.IndexOf("tear", System.StringComparison.OrdinalIgnoreCase) >= 0)
            return name.EndsWith("_L", System.StringComparison.OrdinalIgnoreCase) ? "Tear_L" : "Tear_R";
        if (name.IndexOf("cheek", System.StringComparison.OrdinalIgnoreCase) >= 0) return "Blush";
        return name;
    }

    /// <summary>
    /// Which eye a manga part belongs to: `L` or `R`.
    ///
    /// The four manga prefabs are the same four names twice, once for each eye - nothing in the name says which,
    /// so the side has to be read from where the part sits. In the game's rig `Eye_L` and `Eye_R` are the
    /// anchors: the midpoint between them splits the head, and a part on the eye-bone side of it is that eye.
    /// Mirrored instances sit at a negative scale, which the center position ignores, so a part is placed
    /// before this is asked.
    /// </summary>
    private static string SideOf(UmaContainerCharacter character, Vector3 centre)
    {
        if (character != null)
        {
            Transform eyeL = null, eyeR = null;
            foreach (Transform bone in character.GetComponentsInChildren<Transform>(true))
            {
                if (bone == null) continue;
                if (bone.name == "Eye_L") eyeL = bone;
                else if (bone.name == "Eye_R") eyeR = bone;
            }
            if (eyeL != null && eyeR != null)
            {
                // which side of the head x *is* left is a property of the rig, not of the exporter: compare the
                // part against the bones rather than against an assumed sign
                bool leftIsPositive = eyeL.position.x > eyeR.position.x;
                bool positive = centre.x > (eyeL.position.x + eyeR.position.x) * 0.5f;
                return positive == leftIsPositive ? "L" : "R";
            }
        }
        return centre.x >= 0f ? "L" : "R";
    }

    /// <summary>
    /// The model-level note: what the extra morphs are, where the material-bound ones went, and the object-bound
    /// ones (visibility, eye-manga selection, tears) that no material comment could hold.
    ///
    /// This is the "decode it one day" line. It goes into the model comment, which mmd_tools keeps as
    /// <c>mmd_root</c>, and it names both token grammars and the document that defines them.
    /// </summary>
    private static string ExtraMorphsNote(UmaContainerCharacter character)
    {
        if (character == null) return string.Empty;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return string.Empty;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null || facial.OtherMorphs.Count == 0) return string.Empty;

        var objects = new StringBuilder();
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null) continue;
                if (property.Type == BindProperty.BindType.Texture || property.Type == BindProperty.BindType.Shader)
                    continue;
                // the objects by name, without the runtime's " (Clone)" and without repeats: the eye manga are
                // the same four prefabs twice, once for each eye, and nothing outside the game needs to know.
                // Each is followed by '>' and the materials it is drawn with, because a consumer acts on
                // materials - the object name is not a material name (`pfb_eff_chr_emo_eye_000` is drawn by
                // `mtl_eff_chr_emo_eye_000` here, which happens to look like a rename and is not one).
                var entries = new List<string>();
                if (property.BindPrefabs != null)
                {
                    foreach (GameObject prefab in property.BindPrefabs)
                    {
                        if (prefab == null) continue;
                        string plain = prefab.name.Replace(" (Clone)", "").Replace("(Clone)", "");
                        var materials = new List<string>();
                        foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
                        {
                            // only the renderers the model actually carries: these prefabs can hang a
                            // material on something that is not a mesh (`Lit` on a particle, say), and a token
                            // naming a material that is not in the file is just noise for whoever reads it
                            if (!(renderer is MeshRenderer) && !(renderer is SkinnedMeshRenderer)) continue;
                            foreach (Material part in renderer.sharedMaterials)
                            {
                                if (part == null) continue;
                                string name = part.name.Replace(" (Instance)", "");
                                if (!materials.Contains(name)) materials.Add(name);
                            }
                        }
                        string entry = materials.Count > 0 ? plain + ">" + string.Join("+", materials) : plain;
                        if (!entries.Contains(entry)) entries.Add(entry);
                    }
                }
                objects.Append(objects.Length > 0 ? ";" : "").Append(LocatorName(morph)).Append(':')
                       .Append(property.Type).Append(':').Append(property.Part);
                if (entries.Count > 0) objects.Append(':').Append(string.Join(",", entries));
            }
        }

        var note = new StringBuilder("\n");
        note.Append("extra morphs: material comments carry a 'morph=' token "
                    + "(<morph>:<bind type>:<locator part>:<property>) that drives what a pmx cannot hold; "
                    + "see docs/PMX_EXTENSIONS.md");
        if (objects.Length > 0) note.Append("\nobject morphs: ").Append(objects);
        return note.ToString();
    }

    /// <summary>
    /// The name a morph's driver reads: its locator transform, which is not always the morph's own name.
    /// `StaticTear_Ctrl` is the one that differs - the game drives it from `Cheek_Ctrl`'s position - so the
    /// token has to say `Cheek_Ctrl` or a reader would look for a bone that does not exist.
    /// </summary>
    private static string LocatorName(FacialOtherMorph morph)
    {
        return morph.locator != null ? morph.locator.name : morph.name;
    }

    /// <summary>
    /// Textures the extra morphs bind that no material necessarily uses - the second cheek map is one: the game
    /// swaps it into the same slot when the locator raises the other axis, so it is only ever referenced by the
    /// morph. Without it in the exported folder a consumer cannot swap to it.
    /// </summary>
    public static List<Texture2D> MorphPartTextures(UmaContainerCharacter character)
    {
        var found = new List<Texture2D>();
        if (character == null) return found;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return found;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return found;
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null || property.Type != BindProperty.BindType.Texture) continue;
                if (property.BindTexture is Texture2D texture && !found.Contains(texture)) found.Add(texture);
            }
        }
        return found;
    }

    public static List<Renderer> MorphPartRenderers(UmaContainerCharacter character)
    {
        var found = new List<Renderer>();
        if (character == null) return found;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return found;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return found;
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null) continue;

            // the material-bound part: the object the material is on, the cheek decal
            if (morph.BindGameObject != null)
            {
                foreach (Renderer renderer in morph.BindGameObject.GetComponentsInChildren<Renderer>(true))
                {
                    if (renderer != null && !found.Contains(renderer)) found.Add(renderer);
                }
            }

            // the object-bound parts: the objects the morph shows and hides - the eye manga and the static
            // tears. They are effect prefabs the viewer instantiates and keeps inactive, so they are not in
            // the walk either, and without them a visibility driver has nothing to hide.
            if (morph.BindProperties == null) continue;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null || property.BindPrefabs == null) continue;
                foreach (GameObject prefab in property.BindPrefabs)
                {
                    if (prefab == null) continue;
                    foreach (Renderer renderer in prefab.GetComponentsInChildren<Renderer>(true))
                    {
                        if (renderer != null && !found.Contains(renderer)) found.Add(renderer);
                    }
                }
            }
        }

        // The animated tears are the same kind of part but none of the morphs above owns them: they are runtime
        // instances a `TearController` makes, off until its weight rises. They belong in this list for two
        // reasons - the vertices that make their decals, and their *texture*, which lives on the prefab's own
        // material and not in the character's texture set. This list is also what `ExportAllTexture` walks, so
        // without them here their decals fall back to the first texture in the file (body diffuse).
        if (character.TearControllers != null)
        {
            foreach (TearController tear in character.TearControllers)
            {
                if (tear == null) continue;
                foreach (GameObject tearObject in new GameObject[] { tear.TearObject_0, tear.TearObject_1 })
                {
                    if (tearObject == null) continue;
                    foreach (Renderer renderer in tearObject.GetComponentsInChildren<Renderer>(true))
                    {
                        if (renderer != null && !found.Contains(renderer)) found.Add(renderer);
                    }
                }
            }
        }
        return found;
    }

    private static Part[] ReadPartMaterials(List<Renderer> renderers, RawMMDModel model,
                                            UmaContainerCharacter character, HashSet<Renderer> restInvisible)
    {
        List<Part> parts = new List<Part>();
        int baseShift = 0;

        foreach (Renderer renderer in renderers)
        {
            Mesh mesh;
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                mesh = meshfilter != null ? meshfilter.mesh : null;
            }
            else if (renderer is SkinnedMeshRenderer skinned)
            {
                mesh = skinned.sharedMesh;
            }
            else
            {
                // the effect parts the facial morphs drive are not all meshes (a manga eye can be a particle or
                // a sprite); anything without a mesh is simply not geometry this export can carry
                continue;
            }
            if (mesh == null) continue;
            if (!mesh.isReadable)
            {
                try
                {
                    mesh = MakeReadableMeshCopy(mesh);
                }
                catch
                {
                    UmaViewerUI.Instance.ShowMessage($"Skipping material for non-readable mesh: {mesh.name}", UIMessageType.Warning);
                    // Still need to advance baseShift!
                    baseShift += mesh.triangles.Length; // BUT: this mesh.triangles may fail too!
                    // Better: get triangle count safely
                    int triCount = 0;
                    if (renderer is MeshRenderer mrr)
                        triCount = mrr.GetComponent<MeshFilter>().sharedMesh.triangles.Length;
                    else
                        triCount = ((SkinnedMeshRenderer)renderer).sharedMesh.triangles.Length;
                    baseShift += triCount;
                    continue;
                }
            }
            var materials = new List<Material>(renderer.sharedMaterials);
            for (int i = 0; i < mesh.subMeshCount; i++)
            {
                var material = (i < materials.Count ? materials[i] : materials[materials.Count - 1]);
                var part = new Part();
                var mat = new MMDMaterial();
                part.Material = mat;
                mat.Name = mat.NameEn = material.name.Replace(" (Instance)","");
                mat.DiffuseColor = Color.white;
                bool decal = restInvisible != null && restInvisible.Contains(renderer);
                mat.SpecularColor = Color.clear;
                mat.AmbientColor = Color.white * 0.5f;
                mat.Shiness = 5;
                mat.CastSelfShadow = !decal;
                mat.DrawGroundShadow = !decal;
                mat.DrawSelfShadow = !decal;
                mat.EdgeColor = Color.black;
                mat.EdgeSize = decal ? 0f : 0.4f;
                mat.DrawEdge = !decal;
                // a decal part is hidden by its own geometry, not by its alpha: every vertex of it sits on one
                // point inside the head, so at rest it is a handful of zero-area triangles and draws nothing,
                // and a deploy morph puts it back. The material therefore stays at full alpha - zeroing it
                // would make the *deployed* state invisible as well, which is the whole point of the morph.
                if (decal)
                {
                    // double sided, because a decal is and because these parts arrive through instances the
                    // game mirrors: a mirrored transform reverses the triangle winding, so with backface
                    // culling on the copy for the right eye disappears no matter what its alpha says.
                    mat.DrawDoubleFace = true;
                }
                // The writer writes the comment with no null guard, and MMD treats an empty comment as "none",
                // so every material starts out with an empty one
                mat.MetaInfo = string.Empty;

                if (material.HasProperty("_MainTex") && material.mainTexture != null)
                {
                    try
                    {
                        // a multiply decal is drawn with the baked copy instead: it carries the blush as an
                        // alpha mask, which an MMD material can draw, while the game's own map would paint a
                        // white shell over the cheeks (see TextureExporter.BakeBlush)
                        string textureName = material.mainTexture.name;
                        if (decal && TextureExporter.IsMultiply(material))
                        {
                            textureName = TextureExporter.BlushName(textureName);
                        }
                        var tex = model.TextureList.Find(t => t.TexturePath.Contains($"/{textureName}.png"));
                        if (tex == null)
                        {
                            Debug.LogWarning($"{Tag} {material.name}: texture '{material.mainTexture.name}' is not in the exported "
                                             + "texture list, substituting the first texture - the surface will not look right");
                        }
                        mat.Texture = (tex ?? model.TextureList[0]);
                    }
                    catch (Exception e)
                    {
                        Debug.LogWarning($"{Tag} {material.name}: texture lookup failed ({e.Message}), "
                                         + "substituting the first texture");
                        mat.Texture = model.TextureList[0];
                    }
                }
                else
                {
                    // e.g. environment materials whose texture set is only assigned at runtime by the game
                    Debug.LogWarning($"{Tag} {material.name}: no main texture at all, substituting the first texture - "
                                     + "the surface will not look right (see UmaEnvTextureSet for environment scenes)");
                    mat.Texture = model.TextureList[0];
                }
                // Opt out for models that are meant to be used without the Blender addon: the plain MMD
                // material values set above are then left alone, which is what an unadorned export looks like
                if (Config.Instance == null || Config.Instance.PmxUmaMaterialFields)
                {
                    mat.MetaInfo = UmaMaterialComment(material, model)
                                 + ExtraMorphComment(character, material)
                                 + ExtraMorphBlend(material)
                                 + ExtraMorphGrid(character, renderer);

                    // The uma maps stay out of MMD's sphere and toon slots, both measured by rendering them:
                    //
                    // * the uma environment map is added at the material's own _EnvRate (0.4) by the game, while
                    //   MMD's "sphere add" mode adds it at full strength with no rate to scale it - the model
                    //   came out washed out and glossy
                    // * the uma shade map (shad_c) is the colour of the shaded part of the surface, not a ramp,
                    //   so an MMD toon slot fed with it banded the model into harsh dark steps (black hair)
                    //
                    // Both maps are exported as textures and named in the comment, so a shader that understands
                    // what they are (the uma addon's) can use them properly.
                    mat.Toon = null;
                    mat.SubTexture = null;
                    mat.SubTextureType = MMDMaterial.SubTextureTypeEnum.MatSubTexOff;

                    // MMD's specular is a colour and a shininess; the uma material has a colour and a power on a
                    // different scale, so the power scales the colour down instead of the colour being used as
                    // it is (which made every part look polished).
                    var specular = PropertyColour(material, "_SpecularColor", Color.clear);
                    float specularPower = PropertyFloat(material, "_SpecularPower", 0f);
                    mat.SpecularColor = new Color(specular.r * specularPower, specular.g * specularPower,
                                                  specular.b * specularPower, 1f);
                    mat.EdgeColor = PropertyColour(material, "_OutlineColor", mat.EdgeColor);
                    // a decal keeps the no-outline values set above: the uma shader's own outline width would
                    // wrap the blush and the manga eyes in the character's outline colour
                    if (!decal)
                    {
                        mat.EdgeSize = PropertyFloat(material, "_OutlineWidth", mat.EdgeSize);
                        mat.DrawEdge = mat.EdgeSize > 0f;
                    }
                }
                part.BaseShift = baseShift + mesh.GetSubMesh(i).indexStart;
                part.TriangleIndexNum = mesh.GetSubMesh(i).indexCount;
                parts.Add(part);
            }
            baseShift += mesh.triangles.Length;
        }
        return parts.ToArray();
    }

    private static Vertex[] ReadVerticesAndTriangles(List<Renderer> renderers, List<Transform> bones,
                                                     ref List<int> triangleList, Transform root,
                                                     List<(Renderer renderer, int start, int count)> ranges)
    {
        List<Vertex> verticesList = new List<Vertex>();
        int vertexOffset = 0;

        foreach (Renderer renderer in renderers)
        {
            if (!(renderer is MeshRenderer) && !(renderer is SkinnedMeshRenderer))
            {
                // not a mesh renderer: the facial effect parts can be particles or sprites, and there is no
                // geometry to read from one
                continue;
            }
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                if (meshfilter == null) continue;
                //Cache this data to avoid copying arrays.
                var mesh = meshfilter.mesh;
                if (!mesh.isReadable)
                {
                    UmaViewerUI.Instance.ShowMessage($"Mesh {mesh.name} was not readable. Attempting to export", UIMessageType.Warning);
                    try
                    {
                        mesh = MakeReadableMeshCopy(mesh);
                    }
                    catch
                    {
                        UmaViewerUI.Instance.ShowMessage($"Export {mesh.name} Failed : Mesh is not readable", UIMessageType.Error);
                        continue;
                    }
                }
                var vertices = mesh.vertices;
                var normals = mesh.normals;
                var uv = mesh.uv;
                var uv1 = mesh.uv2;
                var uv2 = mesh.uv3;
                var colors = mesh.colors;
                var triangles = mesh.triangles;

                for (int i = 0; i < vertices.Length; i++)
                {
                    Vertex vertex = new Vertex();
                    vertex.Coordinate = renderer.transform.TransformPoint(vertices[i]);
                    vertex.Normal = normals[i];
                    vertex.UvCoordinate = new Vector2(uv[i].x, 1 - uv[i].y);

                    vertex.ExtraUvCoordinate = new Vector4[3]
                    {
                        uv1.Length > 0 ? new Vector2(uv1[i].x, 1 - uv1[i].y) : Vector2.zero,
                        uv2.Length > 0 ? new Vector2(uv2[i].x, 1 - uv2[i].y) : Vector2.zero,
                        colors.Length > 0 ? colors[i] : Color.clear
                    };

                    vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                    vertex.SkinningOperator.Param = new Bdef1() { BoneId = bones.IndexOf(renderer.transform) };
                    vertex.EdgeScale = 1;
                    verticesList.Add(vertex);
                    if (VertexDumpPath != null) RecordVertex(vertex, renderer.name);
                }


                if (ranges != null) ranges.Add((renderer, vertexOffset, vertices.Length));
                foreach (var triangle in mesh.triangles)
                {
                    triangleList.Add(triangle + vertexOffset);
                }
                vertexOffset += vertices.Length;
            }
            else if (renderer is SkinnedMeshRenderer smr)
            {
                var mesh = smr.sharedMesh;
                Transform headBone = FindHeadBone(bones);
                if (VertexDumpPath != null)
                {
                    _writtenVertices.Add($"# renderer {renderer.name} mesh {mesh.name} "
                                         + $"offset {verticesList.Count} count {mesh.vertexCount} "
                                         + $"readable {mesh.isReadable}");
                }
                if (!mesh.isReadable)
                {
                    UmaViewerUI.Instance.ShowMessage($"Mesh {mesh.name} was not readable. Attempting to export", UIMessageType.Warning);
                    try
                    {
                        mesh = MakeReadableMeshCopy(mesh);
                    }
                    catch
                    {
                        UmaViewerUI.Instance.ShowMessage($"Export {mesh.name} Failed : Mesh is not readable", UIMessageType.Error);
                        continue;
                    }
                }
                var vertices = mesh.vertices;
                var normals = mesh.normals;
                var uv = mesh.uv;
                var uv1 = mesh.uv2;
                var uv2 = mesh.uv3;
                var colors = mesh.colors;
                var boneCounts = mesh.GetBonesPerVertex();
                var skinbone = smr.bones;
                var skinbones = smr.bones;
                var weights = mesh.boneWeights;
                var bakemesh = new Mesh();
                smr.BakeMesh(bakemesh,true);

                for (int i = 0; i < vertices.Length; i++)
                {
                    Vertex vertex = new Vertex();
                    vertex.Coordinate = root.InverseTransformPoint(smr.transform.TransformPoint(bakemesh.vertices[i])); 
                    vertex.Normal = normals[i];
                    vertex.UvCoordinate = new Vector2(uv[i].x, 1 - uv[i].y);
                    // the head-local height goes in the spare .z of the second extra uv, which mmd_tools
                    // reads as `_UV2`; nothing else in the file uses that component
                    float headLocalY = 0f;
                    if (headBone != null)
                    {
                        Vector3 world = smr.transform.TransformPoint(bakemesh.vertices[i]);
                        headLocalY = headBone.worldToLocalMatrix.MultiplyPoint(world).y;
                    }
                    vertex.ExtraUvCoordinate = new Vector4[3]
                    {
                        uv1.Length > 0 ? new Vector2(uv1[i].x, 1 - uv1[i].y) : Vector2.zero,
                        new Vector4(uv2.Length > 0 ? uv2[i].x : 0f,
                                    uv2.Length > 0 ? 1 - uv2[i].y : 0f,
                                    headLocalY, 0f),
                        colors.Length > 0 ? colors[i] : Color.clear
                    };

                    var boneWeight = weights[i];
                    var boneCount = boneCounts[i];

                    switch (boneCount)
                    {
                        case 0:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                            vertex.SkinningOperator.Param = new Bdef1() { BoneId = GetBoneIndex(bones, renderer.transform) };
                            break;

                        default:
                        case 1:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                            vertex.SkinningOperator.Param = new Bdef1() { BoneId = GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]) };
                            break;

                        case 2:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef2 };
                            vertex.SkinningOperator.Param = new Bdef2()
                            {
                                BoneId = new int[]{
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex1]),
                                },
                                BoneWeight = boneWeight.weight0
                            };
                            break;

                        case 3:
                        case 4:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef4 };
                            vertex.SkinningOperator.Param = new Bdef4()
                            {
                                BoneId = new int[]{
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex1]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex2]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex3]),
                                },
                                BoneWeight = new float[]
                                {
                                    boneWeight.weight0,
                                    boneWeight.weight1,
                                    boneWeight.weight2,
                                    boneWeight.weight3
                                }
                            };
                            break;
                    }
                    vertex.EdgeScale = 1;
                    verticesList.Add(vertex);
                    if (VertexDumpPath != null) RecordVertex(vertex, renderer.name);
                }

                if (ranges != null) ranges.Add((renderer, vertexOffset, vertices.Length));
                foreach (var triangle in mesh.triangles)
                {
                    triangleList.Add(triangle + vertexOffset);
                }
                vertexOffset += vertices.Length;
            }
        }
        FlushVertexDump();
        return verticesList.ToArray();
    }

    /// <summary>
    /// When set, every vertex is also recorded here in the order the pmx receives it. Set by the headless
    /// exporter before an export and cleared after; null in normal use, which costs one comparison per
    /// vertex. This exists because comparing the pmx against the live mesh has to be done vertex by vertex,
    /// and a mesh read at a different moment than the write - while the viewer's model is animating - is
    /// not the same vertex list at all.
    /// </summary>
    public static string VertexDumpPath;

    private static readonly List<string> _writtenVertices = new List<string>();

    private static void RecordVertex(Vertex vertex, string rendererName)
    {
        var extra = vertex.ExtraUvCoordinate;
        var parts = new List<string>(24)
        {
            vertex.Coordinate.x.ToString("R"), vertex.Coordinate.y.ToString("R"), vertex.Coordinate.z.ToString("R"),
            vertex.Normal.x.ToString("R"), vertex.Normal.y.ToString("R"), vertex.Normal.z.ToString("R"),
            vertex.UvCoordinate.x.ToString("R"), vertex.UvCoordinate.y.ToString("R"),
        };
        for (int i = 0; i < 3; i++)
        {
            var layer = extra != null && i < extra.Length ? extra[i] : Vector4.zero;
            parts.Add(layer.x.ToString("R"));
            parts.Add(layer.y.ToString("R"));
            parts.Add(layer.z.ToString("R"));
            parts.Add(layer.w.ToString("R"));
        }
        parts.Add(rendererName);
        _writtenVertices.Add(string.Join(" ", parts));
    }

    private static void FlushVertexDump()
    {
        if (VertexDumpPath == null) return;
        File.WriteAllLines(VertexDumpPath, _writtenVertices);
        Debug.Log($"[ModelExporter] wrote {_writtenVertices.Count} written vertices to {VertexDumpPath}");
        _writtenVertices.Clear();
        VertexDumpPath = null;
    }

    private static int GetBoneIndex(List<Transform> bones, Transform bone)
    {
        return bones.Contains(bone) ? bones.IndexOf(bone) : 0;
    }

    /// <summary>
    /// The head bone, whose space the game's facial shadow is measured in: the viewer sets
    /// `_faceShadowHeadMat` from it every frame (`HeadBone.transform.worldToLocalMatrix`) and the vertex
    /// program transforms each vertex by it, so the pixel program can read the vertex's height inside the
    /// head. A static export can carry the same number computed at the rest pose.
    /// </summary>
    private static Transform FindHeadBone(List<Transform> bones)
    {
        foreach (var bone in bones)
        {
            if (bone != null && bone.name == "Head") return bone;
        }
        return null;
    }

    /// <summary> Credit to pohype: https://discussions.unity.com/t/reading-meshes-at-runtime-that-are-not-enabled-for-read-write/804189/7 </summary>
    public static Mesh MakeReadableMeshCopy(Mesh nonReadableMesh)
    {
        Mesh meshCopy = new Mesh();
        meshCopy.indexFormat = nonReadableMesh.indexFormat;

        // Handle vertices
        GraphicsBuffer verticesBuffer = nonReadableMesh.GetVertexBuffer(0);
        int totalSize = verticesBuffer.stride * verticesBuffer.count;
        byte[] data = new byte[totalSize];
        verticesBuffer.GetData(data);
        meshCopy.SetVertexBufferParams(nonReadableMesh.vertexCount, nonReadableMesh.GetVertexAttributes());
        meshCopy.SetVertexBufferData(data, 0, 0, totalSize);
        verticesBuffer.Release();

        // Handle triangles
        meshCopy.subMeshCount = nonReadableMesh.subMeshCount;
        GraphicsBuffer indexesBuffer = nonReadableMesh.GetIndexBuffer();
        int tot = indexesBuffer.stride * indexesBuffer.count;
        byte[] indexesData = new byte[tot];
        indexesBuffer.GetData(indexesData);
        meshCopy.SetIndexBufferParams(indexesBuffer.count, nonReadableMesh.indexFormat);
        meshCopy.SetIndexBufferData(indexesData, 0, 0, tot);
        indexesBuffer.Release();

        // Restore submesh structure
        uint currentIndexOffset = 0;
        for (int i = 0; i < meshCopy.subMeshCount; i++)
        {
            uint subMeshIndexCount = nonReadableMesh.GetIndexCount(i);
            meshCopy.SetSubMesh(i, new SubMeshDescriptor((int)currentIndexOffset, (int)subMeshIndexCount));
            currentIndexOffset += subMeshIndexCount;
        }

        // Recalculate normals and bounds
        meshCopy.RecalculateNormals();
        meshCopy.RecalculateBounds();

        return meshCopy;
    }
