    public static void ExportModel(UmaContainerCharacter container, string path)
    {
        container.SetDynamicBoneEnable(false);
        container.EnablePhysics = false;
        container.UmaFaceAnimator?.Rebind();
        container.UmaAnimator?.Rebind();
        container.EnableEyeTracking = false;
        container.FaceDrivenKeyTarget?.FacialResetAll();
        AddBlendShape(container);
        BuildBillboard(container);

        var textures = TextureExporter.ExportAllTexture(Path.GetDirectoryName(path), container.gameObject,
                                                       MorphPartRenderers(container));
        RawMMDModel model;
        // Reads both the baked vertices and the bone positions, so the rest pose has to be in place for
        // the whole read. A no-op unless Config.PmxAPoseRestPose is set.
        using (UmaAPose.Enter(container))
        {
            model = ReadPMXModel(container, textures, container.CharaEntry);
        }

        if (FbxExporter.IsFbxPath(path))
        {
            WriteFbx(path, model);
            RemoveBillboard(container);
            ClearBlendShape(container);
            return;
        }

        FileStream fileStream = new FileStream(path, FileMode.Create);
        BinaryWriter writer = new BinaryWriter(fileStream);
        var config = new ModelConfig() { GlobalToonPath = "Toon" };
        PMXWriter.Write(writer, model, config);

        writer.Close();
        fileStream.Close();

        RemoveBillboard(container);
        ClearBlendShape(container);
        UmaViewerUI.Instance.ShowMessage($"PMX Save at {path}", UIMessageType.Success);
    }

    public static void ExportModel(UmaContainer container, string path)
    {

        var textures = TextureExporter.ExportAllTexture(Path.GetDirectoryName(path), container.gameObject,
                                                       MorphPartRenderers(container as UmaContainerCharacter));
        var model = ReadPMXModel(container, textures);

        if (FbxExporter.IsFbxPath(path))
        {
            WriteFbx(path, model);
            return;
        }

        // Vertex index size fix
        PmxConfig pmxConfig = new PmxConfig()
            {
                Utf8Encoding = false,
                Encoding = Encoding.Unicode,
                ExtraUvNumber = 3, //include uv2 and color
                VertexIndexSize = model.Vertices.Length > 65535 ? 4 : (model.Vertices.Length > 255 ? 2 : 1),
                TextureIndexSize = model.TextureList.Count > 255 ? 2 : 1,
                MaterialIndexSize = model.Parts.Length > 255 ? 2 : 1,
                BoneIndexSize = model.Bones.Length > 65535 ? 4 : (model.Bones.Length > 255 ? 2 : 1),
                MorphIndexSize = model.Morphs.Length > 65535 ? 4 : (model.Morphs.Length > 255 ? 2 : 1),
                RigidBodyIndexSize = model.Rigidbodies.Length > 65535 ? 4 : (model.Rigidbodies.Length > 255 ? 2 : 1)
            };

        FileStream fileStream = new FileStream(path, FileMode.Create);
        BinaryWriter writer = new BinaryWriter(fileStream);
        var config = new ModelConfig() { GlobalToonPath = "Toon" };
        PMXWriter.Write(writer, model, config, pmxConfig);

        writer.Close();
        fileStream.Close();

        UmaViewerUI.Instance.ShowMessage($"PMX Save at {path}", UIMessageType.Success);
    }

    /// <summary>
    /// Writes the model as FBX instead of PMX. Same model, same code path that read it - only the writer
    /// changes - and the uma refinement step is applied here and nowhere else, so it can be turned off
    /// without touching either writer. The texture paths are the model's own list: the texture exporter has
    /// already written the files next to the model by the time this is called.
    /// </summary>
    public static void WriteFbx(string path, RawMMDModel model)
    {
        FbxExporter.Options options = new FbxExporter.Options
        {
            Creator = $"UmaViewer {Application.version}",
            TextureFolder = "Texture2D",
            EmbedTextures = Config.Instance == null || Config.Instance.FbxEmbedTextures
        };
        bool refine = Config.Instance != null && Config.Instance.FbxApplyUmaRefinement;

        // The helpers go before the skeleton is built: dropping bones renumbers the ones after them, and
        // the skeleton, the skin clusters and the vertex weights all refer to bones by index.
        int omitted = refine ? UmaModelRefinement.OmitHiddenBones(model) : 0;
        FbxExporter.Skeleton skeleton = FbxExporter.Skeleton.FromModel(model, options.LeafBones);

        // The FBX writer converts Unity space to FBX space, so it is worth saying in the log what it was
        // handed: a rig and a mesh that disagree on scale would show up here before it shows up in Blender.
        if (model.Bones != null && model.Bones.Length > 1 && model.Vertices != null && model.Vertices.Length > 0)
        {
            Debug.Log($"{Tag} fbx source: {model.Bones.Length} bones, {model.Bones[0].Name} at "
                      + $"{model.Bones[0].Position}, {model.Bones[1].Name} at {model.Bones[1].Position}; "
                      + $"vertex 0 at {model.Vertices[0].Coordinate}");
        }

        if (refine)
        {
            UmaModelRefinement.Report report = UmaModelRefinement.Apply(model, skeleton);
            report.HiddenBonesOmitted = omitted;
            Debug.Log(Tag + " " + report.Summary());
        }

        Debug.Log($"{Tag} fbx: {skeleton.Bones.Count} bone nodes "
                  + $"({model.Bones.Length} bones and {skeleton.Bones.Count - model.Bones.Length} leaf stubs), "
                  + $"arrays {(options.CompressArrays ? "deflated" : "raw")}"
                  + $", textures {(options.EmbedTextures ? "embedded" : "referenced")}");
        FbxExporter.Write(path, model, skeleton, options);

        UmaViewerUI.Instance.ShowMessage($"FBX Save at {path}", UIMessageType.Success);
    }

    public static RawMMDModel ReadPMXModel(UmaContainer container, string[] textures, CharaEntry entry = null)
    {
        RawMMDModel model = new RawMMDModel();
        var character = container as UmaContainerCharacter;
        string morphNote = ExtraMorphsNote(character);
        if (entry != null)
        {
            model.Name = entry.Name;
            model.NameEn = entry.GetName();
            model.Description = model.DescriptionEn = $"{entry.GetName()}\n{modelInfo}{morphNote}";
        }
        else
        {
            model.Name = container.gameObject.name;
            model.NameEn = container.gameObject.name;
            model.Description = model.DescriptionEn = $"{container.gameObject.name}\n{modelInfo}{morphNote}";
        }

        //Rean Bones
        var rootBone = container.transform.Find("Position");
        if (rootBone == null)
        {
            rootBone = container.transform;
        }
        List<Transform> bones = new List<Transform>(rootBone.GetComponentsInChildren<Transform>());
        bones.RemoveAll(o => o.name.Contains("Col_"));

        //Read vertices And triangles
        List<Renderer> renderers = new List<Renderer>(container.GetComponentsInChildren<Renderer>());
        // the parts a material-bound extra morph drives are inactive, so the walk above misses them. Added
        // here, before the vertices, so their triangles are in the mesh; they are drawn at zero alpha until a
        // driver raises them, which is the state the game has them in at rest.
        var morphParts = MorphPartRenderers(character);
        var restInvisible = new HashSet<Renderer>();
        foreach (Renderer renderer in morphParts)
        {
            if (renderer == null) continue;
            if (!renderers.Contains(renderer)) renderers.Add(renderer);
            restInvisible.Add(renderer);
        }
        List<int> triangles = new List<int>();
        model.Vertices = ReadVerticesAndTriangles(renderers, bones, ref triangles, container.transform);
        model.TriangleIndexes = triangles.ToArray();

        //Read Texture reference
        foreach (var texture in textures)
        {
            model.TextureList.Add(new MMDTexture(texture));
        }

        model.Parts = ReadPartMaterials(renderers, model, character, restInvisible);
        // the locators the extra morphs are bound to, so a driver has a node to read. Added after the vertices
        // are read: the skinning records bone indices, and appending at the end cannot move any of them.
        var locators = Config.Instance == null || Config.Instance.PmxExtraMorphs
            ? MorphLocators(character)
            : new List<Transform>();
        foreach (Transform locator in locators)
        {
            if (!bones.Contains(locator)) bones.Add(locator);
        }

        model.Bones = ReadBones(bones);

        // A locator's transform parent is the locator object, which is not a bone, so it comes back with no
        // parent at all. Hang it off the root bone instead: the skeleton keeps one root and the locator travels
        // with the character, which is where the game keeps it too - a sibling of the body root, not a child.
        if (locators.Count > 0)
        {
            for (int i = 1; i < model.Bones.Length; i++)
            {
                if (model.Bones[i].ParentIndex >= 0) continue;
                if (locators.Exists(locator => locator != null && locator.name == model.Bones[i].Name))
                    model.Bones[i].ParentIndex = 0;
            }
        }
        model.Morphs = ReadMorph(renderers);
        model.Rigidbodies = new MMDRigidBody[0];
        model.Joints = new MMDJoint[0];

        return model;
    }

    public static Vector3[] Vec4ToVec3(Vector4[] vector4s)
    {
        Vector3[] tmp = new Vector3[vector4s.Length];
        for (int i = 0; i < vector4s.Length; i++)
        {
            tmp[i] = new Vector3(vector4s[i].x, vector4s[i].y, vector4s[i].z);
        }
        return tmp;
    }

    public static Vector3[] CalDelta(Vector3[] ori, Vector3[] end)
    {
        Vector3[] tmp = new Vector3[ori.Length];
        for (int i = 0; i < ori.Length; i++)
        {
            tmp[i] = end[i] - ori[i];
        }
        return tmp;
    }

    private static void AddBlendShape(UmaContainerCharacter container)
    {
        if (!container.FaceDrivenKeyTarget) return;
        SkinnedMeshRenderer faceMesh = null;
        SkinnedMeshRenderer eyebrowMesh = null;
        SkinnedMeshRenderer earMesh = null;
        foreach (SkinnedMeshRenderer s in container.GetComponentsInChildren<SkinnedMeshRenderer>())
        {
            if (s.name.Equals("M_Face")) faceMesh = s;
            else if (s.name.Equals("M_Mayu")) eyebrowMesh = s;
            else if (s.name.Equals("M_Hair")) earMesh = s;
        }

        var facial = container.FaceDrivenKeyTarget;
        Action<SkinnedMeshRenderer, List<FacialMorph>, Mesh> addBlendShapePart = delegate (SkinnedMeshRenderer skin, List<FacialMorph> morphs, Mesh baseMesh)
        {
            container.FaceOverrideData = null;
            foreach (var morph in morphs)
            {
                facial.ClearAllWeights();
                morph.weight = 1;
                facial.ChangeMorph();

                Mesh deltaMesh = new Mesh();
                skin.BakeMesh(deltaMesh);
                skin.sharedMesh.AddBlendShapeFrame( $"{morph.name}({morph.tag})[{skin.name}]", 1,
                        CalDelta(baseMesh.vertices, deltaMesh.vertices),
                        CalDelta(baseMesh.normals, deltaMesh.normals),
                        CalDelta(Vec4ToVec3(baseMesh.tangents), Vec4ToVec3(deltaMesh.tangents)));
            }
        };

        if (faceMesh)
        {
            Mesh basefaceMesh = new Mesh();
            faceMesh.BakeMesh(basefaceMesh);
            addBlendShapePart(faceMesh, facial.EyeBrowMorphs, basefaceMesh);
            addBlendShapePart(faceMesh, facial.EyeMorphs, basefaceMesh);
            addBlendShapePart(faceMesh, facial.MouthMorphs, basefaceMesh);
        }
        
        if (eyebrowMesh)
        {
            Mesh baseEyeBrowMesh = new Mesh();
            eyebrowMesh.BakeMesh(baseEyeBrowMesh);
            addBlendShapePart(eyebrowMesh, facial.EyeBrowMorphs, baseEyeBrowMesh);
        }

        if (earMesh)
        {
            Mesh baseEarMesh = new Mesh();
            earMesh.BakeMesh(baseEarMesh);
            addBlendShapePart(earMesh, facial.EarMorphs, baseEarMesh);
        }
            
        facial.ClearAllWeights();
        facial.ChangeMorph();
    }

    private static void ClearBlendShape(UmaContainerCharacter container)
    {
        if (!container.FaceDrivenKeyTarget) return;
        //assuming base meshes do not have any blend shapes
        foreach (SkinnedMeshRenderer s in container.GetComponentsInChildren<SkinnedMeshRenderer>())
        {
            if (s.name.Equals("M_Face") || s.name.Equals("M_Mayu") || s.name.Equals("M_Hair"))
            {
                s.sharedMesh.ClearBlendShapes();
            }
        }
    }

    private static Morph[] ReadMorph(List<Renderer> renderers)
    {
        // Naming is decided in one place so exported models and exported motions agree, see MorphNaming.
        var mode = Config.Instance != null ? Config.Instance.PmxMorphNameMode : PmxMorphNameMode.Unified;

        // Morph name -> accumulated per-vertex offsets. Keyed by name so a morph that exists on
        // several meshes (e.g. the same eyebrow morph baked onto M_Face and M_Mayu) can either be
        // kept apart (tagged names) or merged (the unified/short spellings) depending on the mode.
        Dictionary<string, Morph> morphsByName = new Dictionary<string, Morph>();
        Dictionary<string, Dictionary<int, Vector3>> morphOffsets = new Dictionary<string, Dictionary<int, Vector3>>();
        List<string> morphOrder = new List<string>();
        int vertexOffset = 0;

        foreach (Renderer renderer in renderers)
        {
            Mesh mesh;
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                mesh = meshfilter.mesh;
            }
            else
            {
                mesh = ((SkinnedMeshRenderer)renderer).sharedMesh;
            }
            var vertexCount = mesh.vertexCount;

            for (int i = 0; i < mesh.blendShapeCount; i++) 
            {
                var deltaVertices = new Vector3[vertexCount];
                var deltaNormals = new Vector3[vertexCount];
                var deltaTangents= new Vector3[vertexCount];
                mesh.GetBlendShapeFrameVertices(i, 0, deltaVertices, deltaNormals, deltaTangents);

                string rawName = mesh.GetBlendShapeName(i);
                MorphNaming.TryParse(rawName, null, out MorphNaming.Parts parts);

                foreach (string morphName in MorphNaming.NamesFor(rawName, null, mode))
                {
                    if (!morphsByName.TryGetValue(morphName, out Morph targetMorph))
                    {
                        targetMorph = new Morph();
                        targetMorph.Name = targetMorph.NameEn = morphName;
                        targetMorph.Type = MorphType.MorphTypeVertex;
                        targetMorph.Category = GetMorphCategory(parts);
                        targetMorph.MorphDatas = new VertexMorphData[0];
                        morphsByName[morphName] = targetMorph;
                        morphOffsets[morphName] = new Dictionary<int, Vector3>();
                        morphOrder.Add(morphName);
                    }

                    var offsets = morphOffsets[morphName];
                    for (int j = 0; j < vertexCount; j++)
                    {
                        // Offset ensures the vertices map to the correct mesh in the combined PMX
                        offsets[vertexOffset + j] = deltaVertices[j];
                    }
                }
            }
            vertexOffset += mesh.vertexCount;
        }

        // Materialise the accumulated offsets, ordered by vertex index so the output is deterministic.
        foreach (string morphName in morphOrder)
        {
            var offsets = morphOffsets[morphName];
            var indices = new List<int>(offsets.Keys);
            indices.Sort();
            var datas = new VertexMorphData[indices.Count];
            for (int i = 0; i < indices.Count; i++)
            {
                datas[i] = new VertexMorphData();
                datas[i].VertexIndex = indices[i];
                datas[i].Offset = offsets[indices[i]];
            }
            morphsByName[morphName].MorphDatas = datas;
        }

        return morphOrder.Select(name => morphsByName[name]).ToArray();
    }

    /// <summary>
    /// Morph categories come from the parsed family, not from the spelling of the exported name:
    /// the unified spelling renames "EyeBrow_*" to "Brow_*", which a name sniff would classify as
    /// "other".
    /// </summary>
    private static MorphCategory GetMorphCategory(MorphNaming.Parts parts)
    {
        switch (parts != null ? parts.Family : null)
        {
            case "Mouth": return MorphCategory.MorphCatMouth;
            case "EyeBrow": return MorphCategory.MorphCatEyebrow;
            case "Eye": return MorphCategory.MorphCatEye;
            default: return MorphCategory.MorphCatOther;
        }
    }

    private static Bone[] ReadBones(List<Transform> bonelist)
    {
        List<Bone> pmxbones = new List<Bone>();
        foreach (var bone in bonelist)
        {
            Bone pmxbone = new Bone();
            pmxbone.Name = pmxbone.NameEn = bone.name;
            pmxbone.Position = bone.position;
            pmxbone.ParentIndex = bonelist.IndexOf(bone.parent);
            pmxbone.TransformLevel = 0;
            pmxbone.Visible = true;
            pmxbone.Movable = true;
            pmxbone.Rotatable = true;
            pmxbone.Controllable = true;
            // A PMX bone's tail is either the index of one of its children or an absolute position. The uma
            // rig has no tails, so a child's head becomes the tail - that is what makes Blender draw the bone
            // along its chain.
            pmxbone.ChildBoneVal = BoneTail(bone, bonelist);
            pmxbones.Add(pmxbone);
        }
        return pmxbones.ToArray();
    }

    /// <summary>
    /// How the tail of one bone is written: the head of a child, or an offset from the bone's own position.
    ///
    /// The child is the first one that describes a direction (see <see cref="PMXTailChild"/>), which is the
    /// next joint for every bone of the body - except where the rig's first child is an attachment that sits
    /// off to the side of the chain, which is what the head bone's children are: its first child is a cheek
    /// offset in front of the face, so the head used to point forward instead of up out of the neck. When the
    /// first child turns more than 60 degrees away from the chain the bone belongs to, the child that really
    /// continues that chain wins instead, at most as long as the segment leading into the bone, so that the
    /// head gets a head-length bone pointing up rather than a spike toward the hair.
    ///
    /// Bones with no usable child at all - finger tips, hair and tail ends, and the roll helpers, whose only
    /// child sits on top of themselves - get a tail along the chain they belong to (<see cref="LeafTail"/>).
    /// </summary>
    private static Bone.ChildBone BoneTail(Transform bone, List<Transform> bonelist)
    {
        Transform pmxChild = PMXTailChild(bone, bonelist);
        Vector3 chain = ChainDirection(bone);
        if (FacesForward(bone))
        {
            // the eyes: their tail points out of the face, not along the chain that arrives at them. The rig's
            // bone axes have forward pointing where the character looks (in the exported file that is -z, where
            // the face helpers sit), and the eye bones themselves hang off the head, so the head's forward is
            // what they look along. See FacesForward.
            Vector3 forward = bone.parent != null ? bone.parent.forward : bone.forward;
            if (forward.sqrMagnitude > 1e-8f)
            {
                float length = chain.sqrMagnitude > 1e-10f ? chain.magnitude * 0.5f : 0.1f;
                return OffsetTail(forward.normalized * length);
            }
        }
        if (pmxChild != null && chain.sqrMagnitude > 1e-10f)
        {
            Vector3 delta = pmxChild.position - bone.position;
            bool offChain = Vector3.Dot(delta.normalized, chain.normalized) < 0.5f;
            if (offChain)
            {
                Transform aligned = AlignedChild(bone, bonelist, chain);
                if (aligned != null)
                {
                    Vector3 direction = aligned.position - bone.position;
                    float length = Mathf.Min(direction.magnitude, chain.magnitude);
                    return OffsetTail(direction.normalized * length);
                }
            }
        }
        if (pmxChild != null)
        {
            return new Bone.ChildBone()
            {
                ChildUseId = true,
                Index = bonelist.IndexOf(pmxChild)
            };
        }
        return OffsetTail(LeafTail(bone));
    }

    private static Bone.ChildBone OffsetTail(Vector3 offset)
    {
        return new Bone.ChildBone()
        {
            ChildUseId = false,
            Index = -1,
            Offset = offset
        };
    }

    /// <summary>
    /// The bones whose tail has to point out of the face instead of along the chain that arrives at them:
    /// the eyeballs and the locators that drive them. MMD points an eye bone at the viewer, so that rotating
    /// it around its own axes moves the gaze - carried along the chain (which comes in from the middle of the
    /// head, up and out towards the temple) a gaze rotation reads as a roll instead, and the eyes look inward.
    /// The direction comes from the bone's own forward axis, which on this rig points where the character
    /// looks; the length stays the same as any other leaf tail, half the segment leading into the bone.
    /// </summary>
    private static bool FacesForward(Transform bone)
    {
        switch (bone.name)
        {
            case "Eye_L":
            case "Eye_R":
            case "Eye_locator_L":
            case "Eye_locator_R":
            case "Eye_target_locator_L":
            case "Eye_target_locator_R":
                return true;
            default:
                return false;
        }
    }

    /// <summary>
    /// The usable child that best continues a chain: the one whose direction lies closest to
    /// <paramref name="chain"/>, and only if it is nearly along it (<see cref="alignedDot"/>). Null when no
    /// child is close enough, which is the case for a bone that really does turn a corner, such as the
    /// shoulder, whose only child is the upper arm.
    /// </summary>
    private static Transform AlignedChild(Transform bone, List<Transform> bonelist, Vector3 chain,
                                          float alignedDot = 0.94f)
    {
        Transform best = null;
        float bestAlignment = alignedDot;
        for (int i = 0; i < bone.childCount; i++)
        {
            Transform child = bone.GetChild(i);
            if (bonelist.IndexOf(child) < 0) continue;
            if (child.name.Contains("_Handle")) continue;
            Transform candidate = child;
            Vector3 delta = candidate.position - bone.position;
            if (delta.sqrMagnitude < 1e-10f)
            {
                // look through a child sitting on the bone, the same way the tail itself does
                candidate = PMXTailChild(child, bonelist, 0);
                if (candidate == null) continue;
                delta = candidate.position - bone.position;
                if (delta.sqrMagnitude < 1e-10f) continue;
            }
            float alignment = Vector3.Dot(delta.normalized, chain.normalized);
            if (alignment > bestAlignment)
            {
                bestAlignment = alignment;
                best = candidate;
            }
        }
        return best;
    }

    /// <summary>
    /// The first child that describes a direction: one that is in the export, not a "_Handle" helper, and not
    /// sitting at the bone's own position. Children that were filtered out of the export (the Col_* colliders)
    /// and the "_Handle" helpers describe no direction at all.
    ///
    /// A child sitting exactly on the bone describes no direction either, but the chain can still continue
    /// through it: the ankle's own children are the ankle offset and the IK handle, both exactly on the ankle,
    /// and the toe that continues the foot hangs off the offset. Looking one level further in matches what a
    /// known-good MMD model does with its ankle - measured on four of them, 足首 points down and forward
    /// towards the toes, never straight down the way the knee segment arrives.
    /// </summary>
    private static Transform PMXTailChild(Transform bone, List<Transform> bonelist, int depth = 1)
    {
        for (int i = 0; i < bone.childCount; i++)
        {
            Transform child = bone.GetChild(i);
            if (bonelist.IndexOf(child) < 0) continue;
            if (child.name.Contains("_Handle")) continue;
            if ((child.position - bone.position).sqrMagnitude > 1e-10f) return child;
            if (depth > 0)
            {
                Transform deeper = PMXTailChild(child, bonelist, depth - 1);
                if (deeper != null) return deeper;
            }
        }
        return null;
    }

    /// <summary>
    /// The direction the chain runs in as it arrives at this bone: the segment from its parent to itself, or
    /// - for a bone sitting exactly on its parent, which is how the uma rig places the roll helpers - the
    /// first ancestor segment that is not degenerate. Zero when there is none, e.g. for the root.
    /// </summary>
    private static Vector3 ChainDirection(Transform bone)
    {
        for (Transform current = bone; current != null; current = current.parent)
        {
            if (current.parent == null) break;
            Vector3 delta = current.position - current.parent.position;
            if (delta.sqrMagnitude > 1e-10f) return delta;
        }
        return Vector3.zero;
    }

    /// <summary>
    /// The tail offset for a bone with nothing usable below it: half of the direction the chain runs in, so
    /// that a finger tip carries on the finger and a roll helper points along the arm or forearm it rolls -
    /// away from the body on both sides, instead of following its own local axes (a mirrored rig does not lay
    /// those out the same way on both sides, which used to point one roll helper at the neck).
    ///
    /// A bone that describes no direction at all (a root, or a bone whose whole ancestry is degenerate) falls
    /// back to the direction of its first child that has one, and otherwise to a short stub, so that there is
    /// always something to draw.
    ///
    /// The value is an offset from the bone's own position, not a position: mmd_tools reads it as
    /// <c>tail = head + offset</c> (core/pmx/importer.py), and its own exporter writes it the same way.
    /// </summary>
    private static Vector3 LeafTail(Transform bone)
    {
        Vector3 segment = ChainDirection(bone);
        if (segment.sqrMagnitude > 1e-10f) return segment * 0.5f;

        for (int i = 0; i < bone.childCount; i++)
        {
            Vector3 delta = bone.GetChild(i).position - bone.position;
            if (delta.sqrMagnitude > 1e-10f) return delta * 0.5f;
        }
        // nothing around it describes a direction: a stub along the bone's own up, which at least keeps the
        // bone visible in a bone list that only stores head, tail and roll
        return bone.up * 0.1f;
    }

    /// <summary>
    /// The exported texture a uma material uses for one of its maps, found in the model's texture list the
    /// same way the albedo is (by file name). Null when the material has no such map, or when the texture
    /// did not make it into the export - the caller decides what to do without it.
    /// </summary>
    private static MMDTexture FindExportedTexture(RawMMDModel model, Material material, string property)
    {
        if (material == null || !material.HasProperty(property)) return null;
        var texture = material.GetTexture(property) as Texture2D;
        if (texture == null) return null;

        var match = model.TextureList.Find(t => t.TexturePath.Contains($"/{texture.name}.png"));
        if (match == null)
        {
            Debug.LogWarning($"{Tag} {material.name}: the {property} texture '{texture.name}' is not in the "
                             + "exported texture list, so that map is missing from the export");
        }
        return match;
    }

    private static float PropertyFloat(Material material, string property, float fallback)
    {
        return material != null && material.HasProperty(property) ? material.GetFloat(property) : fallback;
    }

    private static Color PropertyColour(Material material, string property, Color fallback)
    {
        return material != null && material.HasProperty(property) ? material.GetColor(property) : fallback;
    }

    /// <summary>
    /// The uma shader parameters an MMD material has no field for, written into the material comment as one
    /// line of key=value pairs. mmd_tools imports that comment onto the material
    /// (<c>material.mmd_material.comment</c>), and the uma addon's Shading operator reads it back to set its
    /// shader up with the values this model was exported with instead of its own defaults. Anything that does
    /// not know about it sees a comment, and a property the game renames is skipped rather than breaking the
    /// export - which is also how a rename will be noticed.
    ///
    /// Values use dots for decimals and commas only between the components of a colour, and the numbers are
    /// written with the invariant culture so that a machine with a comma decimal separator cannot produce a
    /// comment that parses as something else.
    /// </summary>
    private static string UmaMaterialComment(Material material, RawMMDModel model)
    {
        if (material == null) return "";

        var comment = new StringBuilder("uma1");
        void Number(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            comment.Append(' ').Append(key).Append('=')
                   .Append(material.GetFloat(property).ToString("0.####", CultureInfo.InvariantCulture));
        }
        void Tint(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            Color colour = material.GetColor(property);
            comment.Append(' ').Append(key).Append('=').Append(string.Join(",",
                colour.r.ToString("0.###", CultureInfo.InvariantCulture),
                colour.g.ToString("0.###", CultureInfo.InvariantCulture),
                colour.b.ToString("0.###", CultureInfo.InvariantCulture),
                colour.a.ToString("0.###", CultureInfo.InvariantCulture)));
        }
        void Vector(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            Vector4 value = material.GetVector(property);
            comment.Append(' ').Append(key).Append('=').Append(string.Join(",",
                value.x.ToString("0.####", CultureInfo.InvariantCulture),
                value.y.ToString("0.####", CultureInfo.InvariantCulture),
                value.z.ToString("0.####", CultureInfo.InvariantCulture),
                value.w.ToString("0.####", CultureInfo.InvariantCulture)));
        }
        void Map(string key, string property)
        {
            if (!material.HasProperty(property)) return;
            var texture = material.GetTexture(property) as Texture2D;
            if (texture == null) return;
            comment.Append(' ').Append(key).Append('=').Append(texture.name);
        }

        // the shade ramp and the light threshold are what the Blender shader group calls "Shaded Texture"
        // and "Light Threshold"
        Number("toon_step", "_ToonStep");
        Number("toon_feather", "_ToonFeather");
        Number("specular_power", "_SpecularPower");
        Tint("specular", "_SpecularColor");
        Number("env_rate", "_EnvRate");
        Number("env_bias", "_EnvBias");
        Number("rim_step", "_RimStep");
        Number("rim_feather", "_RimFeather");
        Tint("rim", "_RimColor");
        Number("rim_spec_rate", "_RimSpecRate");
        Number("rim_shadow", "_RimShadow");
        Number("outline_width", "_OutlineWidth");
        Tint("outline", "_OutlineColor");
        Tint("chara", "_CharaColor");
        Number("saturation", "_Saturation");
        Tint("toon_bright", "_ToonBrightColor");
        Tint("toon_dark", "_ToonDarkColor");
        Number("emissive_intensity", "_EmissiveIntensity");
        Number("emissive_rim_power", "_EmissiveRimPower");
        Number("emissive_rim_intensity", "_EmissiveRimIntensity");
        Number("use_option_mask", "_UseOptionMaskMap");

        // what the game's face shader needs and an MMD material has no field for. _faceShadow* gates the cheek and
        // nose regions, so without them the addon cannot tell a character whose regions are on from one whose are
        // off; _NormalizeNormal 0 means the game uses the raw vertex normal rather than a normalised one.
        //
        // _CylinderBlend comes from the material, and after this round it is the *shipped asset's* value rather
        // than an override: the game sets the rim, toon and saturation values at runtime
        // (Gallop/Live/Director.cs:215-258) and never sets this one, so the asset's value is what the game
        // renders with. The viewer used to force 0.25 here, which the exporter then carried; that override is
        // gone. The cost of the change was measured at 0.04 of a level on the face crop's mean luminance.
        Number("cylinder_blend", "_CylinderBlend");
        Number("normalize_normal", "_NormalizeNormal");
        Number("face_shadow_end_y", "_faceShadowEndY");
        Number("face_shadow_length", "_faceShadowLength");
        // the alpha that gates the region path. In the game it is *driven*: Gallop/FaceDrivenKeyTarget binds it,
        // with no curve between them, to the X scale of a locator named "Shade_Ctrl" (BindProperty.LocatorPart.ScaX,
        // Type Shader, PropertyName "_faceShadowAlpha"). That locator is neither a bone nor a morph in the exported
        // skeleton - the export has no node by that name at all - so what a static pmx can carry is the rest value.
        // Writing it means a character whose material does set the alpha renders its regions with nobody forcing it.
        Number("face_shadow_alpha", "_faceShadowAlpha");
        Tint("face_shadow_color", "_faceShadowColor");
        // the two strengths the region gates compare `factor >= 1 - strength` against: named for exactly
        // that role, and 0.775 makes a threshold the factor can actually cross
        Number("cheek_threshold", "_CheekPretenseThreshold");
        Number("nose_threshold", "_NosePretenseThreshold");
        Number("vertex_color_toon_power", "_VertexColorToonPower");
        Vector("original_light", "_OriginalDirectionalLightDir");

        // The region colours, and they are per character: the viewer sets all twelve from the character's own
        // colour data rows at runtime (UmaContainerCharacter.SetMaskColor), so an export that omits them leaves the
        // region path with nothing to switch between. Six for the surface and six for the toon side, R/G/B in
        // pairs, matching the six colour constants the game's pixel program uses.
        // (The region's own gate, _faceShadowAlpha, is written above with the other face-shader values. It is a
        // *driven* property of the facial driven-key system - Gallop/FaceDrivenKeyTarget binds it to the X scale
        // of a locator named "Shade_Ctrl" - so what the export can carry is its rest value. See the note there.)
        Tint("mask_r1", "_MaskColorR1");
        Tint("mask_r2", "_MaskColorR2");
        Tint("mask_g1", "_MaskColorG1");
        Tint("mask_g2", "_MaskColorG2");
        Tint("mask_b1", "_MaskColorB1");
        Tint("mask_b2", "_MaskColorB2");
        Tint("mask_toon_r1", "_MaskToonColorR1");
        Tint("mask_toon_r2", "_MaskToonColorR2");
        Tint("mask_toon_g1", "_MaskToonColorG1");
        Tint("mask_toon_g2", "_MaskToonColorG2");
        Tint("mask_toon_b1", "_MaskToonColorB1");
        Tint("mask_toon_b2", "_MaskToonColorB2");

        // the maps an MMD material has no field for, by name so the addon does not have to guess file names
        Map("triple", "_TripleMaskMap");
        Map("option", "_OptionMaskMap");
        Map("toon", "_ToonMap");
        Map("env", "_EnvMap");
        Map("emissive", "_EmissiveTex");
        return comment.ToString();
    }

    /// <summary>
    /// The extra facial morphs that touch a material, as one <c>morph=</c> token in its comment.
    ///
    /// An MMD material has no slot for a texture swap or a shader property, but it does have a comment, and the
    /// uma addon reads it back (<c>material.mmd_material.comment</c>). The grammar is one token per material,
    /// holding every morph that binds it: <c>morph=&lt;morph&gt;:&lt;bind type&gt;:&lt;locator part&gt;:&lt;property&gt;[, ...]</c>,
    /// so the cheek decal reads <c>morph=Cheek_Ctrl:Texture:ScaX:_CheekRate,ScaY:_CheekRate,ScaZ:_CheekRate</c>.
    /// The locator part is the axis of the transform the game's own animation drives; turning that into a
    /// driver is the addon's job. Anything that does not know the token sees a comment.
    /// </summary>
    private static string ExtraMorphComment(UmaContainerCharacter character, Material material)
    {
        if (character == null || material == null) return string.Empty;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return string.Empty;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return string.Empty;

        string target = material.name.Replace(" (Instance)", "");
        var morphs = new StringBuilder();
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            var bindings = new StringBuilder();
            string type = null;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null || property.BindMaterial == null) continue;
                if (property.Type != BindProperty.BindType.Texture && property.Type != BindProperty.BindType.Shader)
                    continue;
                if (property.BindMaterial.name.Replace(" (Instance)", "") != target) continue;
                bindings.Append(bindings.Length > 0 ? "," : "").Append(property.Part).Append(':')
                        .Append(property.PropertyName);
                type = property.Type.ToString();
            }
            if (bindings.Length == 0) continue;
            morphs.Append(morphs.Length > 0 ? ";" : "").Append(LocatorName(morph)).Append(':').Append(type)
                  .Append(':').Append(bindings);
        }
        return morphs.Length == 0 ? string.Empty : " morph=" + morphs;
    }

    /// <summary>
    /// The model-level note: what the extra morphs are, where the material-bound ones went, and the object-bound
    /// ones (visibility, eye-manga selection, tears) that no material comment could hold.
    ///
    /// This is the "decode it one day" line. It goes into the model comment, which mmd_tools keeps as
    /// <c>mmd_root</c>, and it names both token grammars and the document that defines them.
    /// </summary>
    private static string ExtraMorphsNote(UmaContainerCharacter character)
    {
        if (character == null) return string.Empty;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return string.Empty;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null || facial.OtherMorphs.Count == 0) return string.Empty;

        var objects = new StringBuilder();
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindProperties == null) continue;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null) continue;
                if (property.Type == BindProperty.BindType.Texture || property.Type == BindProperty.BindType.Shader)
                    continue;
                // the objects by name, without the runtime's " (Clone)" and without repeats: the eye manga are
                // the same four prefabs twice, once for each eye, and nothing outside the game needs to know
                var names = new List<string>();
                if (property.BindPrefabs != null)
                {
                    foreach (GameObject prefab in property.BindPrefabs)
                    {
                        if (prefab == null) continue;
                        string plain = prefab.name.Replace(" (Clone)", "").Replace("(Clone)", "");
                        if (!names.Contains(plain)) names.Add(plain);
                    }
                }
                objects.Append(objects.Length > 0 ? ";" : "").Append(LocatorName(morph)).Append(':')
                       .Append(property.Type).Append(':').Append(property.Part);
                if (names.Count > 0) objects.Append(':').Append(string.Join(",", names));
            }
        }

        var note = new StringBuilder("\n");
        note.Append("extra morphs: material comments carry a 'morph=' token "
                    + "(<morph>:<bind type>:<locator part>:<property>) that drives what a pmx cannot hold; "
                    + "see docs/PMX_EXTENSIONS.md");
        if (objects.Length > 0) note.Append("\nobject morphs: ").Append(objects);
        return note.ToString();
    }

    /// <summary>
    /// The transforms the extra facial morphs are driven by - <c>Cheek_Ctrl</c>, <c>Shade_Ctrl</c>,
    /// <c>Manga_Ctrl</c>, <c>Tear{n}_Ctrl</c>.
    ///
    /// The game builds these on a <c>DrivenKeyLocator</c> object at runtime instead of putting them in the body
    /// skeleton (<c>UmaContainerCharacter.cs</c> instantiates the object as a sibling of the body root), so an
    /// export that only walks the body has no node for a driver to read and the <c>morph=</c> description in
    /// the comment points at nothing.
    /// </summary>
    /// <summary>
    /// The name a morph's driver reads: its locator transform, which is not always the morph's own name.
    /// `StaticTear_Ctrl` is the one that differs - the game drives it from `Cheek_Ctrl`'s position, because a
    /// tear morph has no locator of its own - so the token has to say `Cheek_Ctrl` or a reader would look for
    /// a bone that does not exist.
    /// </summary>
    private static string LocatorName(FacialOtherMorph morph)
    {
        return morph.locator != null ? morph.locator.name : morph.name;
    }

    private static List<Transform> MorphLocators(UmaContainerCharacter character)
    {
        var locators = new List<Transform>();
        if (character == null) return locators;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return locators;
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.locator == null) continue;
            if (!locators.Contains(morph.locator)) locators.Add(morph.locator);
        }
        return locators;
    }

    /// <summary>
    /// The renderers a material-bound extra morph drives - the cheek decal, on a normal character.
    ///
    /// It is switched off in the viewer (`UmaContainerCharacter.cs:912-914`, `SetActive(false)`) because the
    /// game only draws it once a driven key raises `_CheekRate`, and an inactive renderer is not in
    /// `GetComponentsInChildren<Renderer>()`. So the walk over the character misses it, its material never
    /// reaches the pmx, and a `morph=` token for it would have no material to sit on.
    ///
    /// Only the parts these morphs bind are added, not every inactive renderer: the rest of the inactive set
    /// is hidden variants and effect clones that an export should not start carrying.
    /// </summary>
    public static List<Renderer> MorphPartRenderers(UmaContainerCharacter character)
    {
        var found = new List<Renderer>();
        if (character == null) return found;
        if (Config.Instance != null && !Config.Instance.PmxExtraMorphs) return found;
        FaceDrivenKeyTarget facial = character.FaceDrivenKeyTarget;
        if (facial == null || facial.OtherMorphs == null) return found;
        foreach (FacialOtherMorph morph in facial.OtherMorphs)
        {
            if (morph == null || morph.BindGameObject == null || morph.BindProperties == null) continue;
            bool materialBound = false;
            foreach (BindProperty property in morph.BindProperties)
            {
                if (property == null) continue;
                if (property.Type == BindProperty.BindType.Texture || property.Type == BindProperty.BindType.Shader)
                    materialBound = true;
            }
            if (!materialBound) continue;
            foreach (Renderer renderer in morph.BindGameObject.GetComponentsInChildren<Renderer>(true))
            {
                if (renderer != null && !found.Contains(renderer)) found.Add(renderer);
            }
        }
        return found;
    }

    private static Part[] ReadPartMaterials(List<Renderer> renderers, RawMMDModel model,
                                            UmaContainerCharacter character, HashSet<Renderer> restInvisible)
    {
        List<Part> parts = new List<Part>();
        int baseShift = 0;

        foreach (Renderer renderer in renderers)
        {
            Mesh mesh;
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                mesh = meshfilter.mesh;
            }
            else
            {
                mesh = ((SkinnedMeshRenderer)renderer).sharedMesh;
            }
            if (!mesh.isReadable)
            {
                try
                {
                    mesh = MakeReadableMeshCopy(mesh);
                }
                catch
                {
                    UmaViewerUI.Instance.ShowMessage($"Skipping material for non-readable mesh: {mesh.name}", UIMessageType.Warning);
                    // Still need to advance baseShift!
                    baseShift += mesh.triangles.Length; // BUT: this mesh.triangles may fail too!
                    // Better: get triangle count safely
                    int triCount = 0;
                    if (renderer is MeshRenderer mrr)
                        triCount = mrr.GetComponent<MeshFilter>().sharedMesh.triangles.Length;
                    else
                        triCount = ((SkinnedMeshRenderer)renderer).sharedMesh.triangles.Length;
                    baseShift += triCount;
                    continue;
                }
            }
            var materials = new List<Material>(renderer.sharedMaterials);
            for (int i = 0; i < mesh.subMeshCount; i++)
            {
                var material = (i < materials.Count ? materials[i] : materials[materials.Count - 1]);
                var part = new Part();
                var mat = new MMDMaterial();
                part.Material = mat;
                mat.Name = mat.NameEn = material.name.Replace(" (Instance)","");
                mat.DiffuseColor = Color.white;
                // a morph-driven part is invisible at rest: the game's `_CheekRate` is 0 until a driven key
                // raises it, so the decal multiplies nothing. Exporting it at full alpha would paint the
                // blush onto every model whether or not anything drives it.
                if (restInvisible != null && restInvisible.Contains(renderer))
                {
                    mat.DiffuseColor = new Color(1f, 1f, 1f, 0f);
                }
                mat.SpecularColor = Color.clear;
                mat.AmbientColor = Color.white * 0.5f;
                mat.Shiness = 5;
                mat.CastSelfShadow = true;
                mat.DrawGroundShadow = true;
                mat.DrawSelfShadow = true;
                mat.EdgeColor = Color.black;
                mat.EdgeSize = 0.4f;
                // The writer writes the comment with no null guard, and MMD treats an empty comment as "none",
                // so every material starts out with an empty one
                mat.MetaInfo = string.Empty;

                if (material.HasProperty("_MainTex") && material.mainTexture != null)
                {
                    try
                    {
                        var tex = model.TextureList.Find(t => t.TexturePath.Contains($"/{material.mainTexture.name}.png"));
                        if (tex == null)
                        {
                            Debug.LogWarning($"{Tag} {material.name}: texture '{material.mainTexture.name}' is not in the exported "
                                             + "texture list, substituting the first texture - the surface will not look right");
                        }
                        mat.Texture = (tex ?? model.TextureList[0]);
                    }
                    catch (Exception e)
                    {
                        Debug.LogWarning($"{Tag} {material.name}: texture lookup failed ({e.Message}), "
                                         + "substituting the first texture");
                        mat.Texture = model.TextureList[0];
                    }
                }
                else
                {
                    // e.g. environment materials whose texture set is only assigned at runtime by the game
                    Debug.LogWarning($"{Tag} {material.name}: no main texture at all, substituting the first texture - "
                                     + "the surface will not look right (see UmaEnvTextureSet for environment scenes)");
                    mat.Texture = model.TextureList[0];
                }
                // Opt out for models that are meant to be used without the Blender addon: the plain MMD
                // material values set above are then left alone, which is what an unadorned export looks like
                if (Config.Instance == null || Config.Instance.PmxUmaMaterialFields)
                {
                    mat.MetaInfo = UmaMaterialComment(material, model)
                                 + ExtraMorphComment(character, material);

                    // The uma maps stay out of MMD's sphere and toon slots, both measured by rendering them:
                    //
                    // * the uma environment map is added at the material's own _EnvRate (0.4) by the game, while
                    //   MMD's "sphere add" mode adds it at full strength with no rate to scale it - the model
                    //   came out washed out and glossy
                    // * the uma shade map (shad_c) is the colour of the shaded part of the surface, not a ramp,
                    //   so an MMD toon slot fed with it banded the model into harsh dark steps (black hair)
                    //
                    // Both maps are exported as textures and named in the comment, so a shader that understands
                    // what they are (the uma addon's) can use them properly.
                    mat.Toon = null;
                    mat.SubTexture = null;
                    mat.SubTextureType = MMDMaterial.SubTextureTypeEnum.MatSubTexOff;

                    // MMD's specular is a colour and a shininess; the uma material has a colour and a power on a
                    // different scale, so the power scales the colour down instead of the colour being used as
                    // it is (which made every part look polished).
                    var specular = PropertyColour(material, "_SpecularColor", Color.clear);
                    float specularPower = PropertyFloat(material, "_SpecularPower", 0f);
                    mat.SpecularColor = new Color(specular.r * specularPower, specular.g * specularPower,
                                                  specular.b * specularPower, 1f);
                    mat.EdgeColor = PropertyColour(material, "_OutlineColor", mat.EdgeColor);
                    mat.EdgeSize = PropertyFloat(material, "_OutlineWidth", mat.EdgeSize);
                    mat.DrawEdge = mat.EdgeSize > 0f;
                }
                part.BaseShift = baseShift + mesh.GetSubMesh(i).indexStart;
                part.TriangleIndexNum = mesh.GetSubMesh(i).indexCount;
                parts.Add(part);
            }
            baseShift += mesh.triangles.Length;
        }
        return parts.ToArray();
    }

    private static Vertex[] ReadVerticesAndTriangles(List<Renderer> renderers, List<Transform> bones, ref List<int> triangleList, Transform root)
    {
        List<Vertex> verticesList = new List<Vertex>();
        int vertexOffset = 0;

        foreach (Renderer renderer in renderers)
        {
            if (renderer is MeshRenderer mr)
            {
                var meshfilter = mr.GetComponent<MeshFilter>();
                //Cache this data to avoid copying arrays.
                var mesh = meshfilter.mesh;
                if (!mesh.isReadable)
                {
                    UmaViewerUI.Instance.ShowMessage($"Mesh {mesh.name} was not readable. Attempting to export", UIMessageType.Warning);
                    try
                    {
                        mesh = MakeReadableMeshCopy(mesh);
                    }
                    catch
                    {
                        UmaViewerUI.Instance.ShowMessage($"Export {mesh.name} Failed : Mesh is not readable", UIMessageType.Error);
                        continue;
                    }
                }
                var vertices = mesh.vertices;
                var normals = mesh.normals;
                var uv = mesh.uv;
                var uv1 = mesh.uv2;
                var uv2 = mesh.uv3;
                var colors = mesh.colors;
                var triangles = mesh.triangles;

                for (int i = 0; i < vertices.Length; i++)
                {
                    Vertex vertex = new Vertex();
                    vertex.Coordinate = renderer.transform.TransformPoint(vertices[i]);
                    vertex.Normal = normals[i];
                    vertex.UvCoordinate = new Vector2(uv[i].x, 1 - uv[i].y);

                    vertex.ExtraUvCoordinate = new Vector4[3]
                    {
                        uv1.Length > 0 ? new Vector2(uv1[i].x, 1 - uv1[i].y) : Vector2.zero,
                        uv2.Length > 0 ? new Vector2(uv2[i].x, 1 - uv2[i].y) : Vector2.zero,
                        colors.Length > 0 ? colors[i] : Color.clear
                    };

                    vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                    vertex.SkinningOperator.Param = new Bdef1() { BoneId = bones.IndexOf(renderer.transform) };
                    vertex.EdgeScale = 1;
                    verticesList.Add(vertex);
                    if (VertexDumpPath != null) RecordVertex(vertex, renderer.name);
                }


                foreach (var triangle in mesh.triangles)
                {
                    triangleList.Add(triangle + vertexOffset);
                }
                vertexOffset += vertices.Length;
            }
            else if (renderer is SkinnedMeshRenderer smr)
            {
                var mesh = smr.sharedMesh;
                Transform headBone = FindHeadBone(bones);
                if (VertexDumpPath != null)
                {
                    _writtenVertices.Add($"# renderer {renderer.name} mesh {mesh.name} "
                                         + $"offset {verticesList.Count} count {mesh.vertexCount} "
                                         + $"readable {mesh.isReadable}");
                }
                if (!mesh.isReadable)
                {
                    UmaViewerUI.Instance.ShowMessage($"Mesh {mesh.name} was not readable. Attempting to export", UIMessageType.Warning);
                    try
                    {
                        mesh = MakeReadableMeshCopy(mesh);
                    }
                    catch
                    {
                        UmaViewerUI.Instance.ShowMessage($"Export {mesh.name} Failed : Mesh is not readable", UIMessageType.Error);
                        continue;
                    }
                }
                var vertices = mesh.vertices;
                var normals = mesh.normals;
                var uv = mesh.uv;
                var uv1 = mesh.uv2;
                var uv2 = mesh.uv3;
                var colors = mesh.colors;
                var boneCounts = mesh.GetBonesPerVertex();
                var skinbone = smr.bones;
                var skinbones = smr.bones;
                var weights = mesh.boneWeights;
                var bakemesh = new Mesh();
                smr.BakeMesh(bakemesh,true);

                for (int i = 0; i < vertices.Length; i++)
                {
                    Vertex vertex = new Vertex();
                    vertex.Coordinate = root.InverseTransformPoint(smr.transform.TransformPoint(bakemesh.vertices[i])); 
                    vertex.Normal = normals[i];
                    vertex.UvCoordinate = new Vector2(uv[i].x, 1 - uv[i].y);
                    // the head-local height goes in the spare .z of the second extra uv, which mmd_tools
                    // reads as `_UV2`; nothing else in the file uses that component
                    float headLocalY = 0f;
                    if (headBone != null)
                    {
                        Vector3 world = smr.transform.TransformPoint(bakemesh.vertices[i]);
                        headLocalY = headBone.worldToLocalMatrix.MultiplyPoint(world).y;
                    }
                    vertex.ExtraUvCoordinate = new Vector4[3]
                    {
                        uv1.Length > 0 ? new Vector2(uv1[i].x, 1 - uv1[i].y) : Vector2.zero,
                        new Vector4(uv2.Length > 0 ? uv2[i].x : 0f,
                                    uv2.Length > 0 ? 1 - uv2[i].y : 0f,
                                    headLocalY, 0f),
                        colors.Length > 0 ? colors[i] : Color.clear
                    };

                    var boneWeight = weights[i];
                    var boneCount = boneCounts[i];

                    switch (boneCount)
                    {
                        case 0:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                            vertex.SkinningOperator.Param = new Bdef1() { BoneId = GetBoneIndex(bones, renderer.transform) };
                            break;

                        default:
                        case 1:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef1 };
                            vertex.SkinningOperator.Param = new Bdef1() { BoneId = GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]) };
                            break;

                        case 2:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef2 };
                            vertex.SkinningOperator.Param = new Bdef2()
                            {
                                BoneId = new int[]{
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex1]),
                                },
                                BoneWeight = boneWeight.weight0
                            };
                            break;

                        case 3:
                        case 4:
                            vertex.SkinningOperator = new SkinningOperator() { Type = SkinningType.SkinningBdef4 };
                            vertex.SkinningOperator.Param = new Bdef4()
                            {
                                BoneId = new int[]{
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex0]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex1]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex2]),
                                    GetBoneIndex(bones, skinbone[boneWeight.boneIndex3]),
                                },
                                BoneWeight = new float[]
                                {
                                    boneWeight.weight0,
                                    boneWeight.weight1,
                                    boneWeight.weight2,
                                    boneWeight.weight3
                                }
                            };
                            break;
                    }
                    vertex.EdgeScale = 1;
                    verticesList.Add(vertex);
                    if (VertexDumpPath != null) RecordVertex(vertex, renderer.name);
                }

                foreach (var triangle in mesh.triangles)
                {
                    triangleList.Add(triangle + vertexOffset);
                }
                vertexOffset += vertices.Length;
            }
        }
        FlushVertexDump();
        return verticesList.ToArray();
    }

    /// <summary>
    /// When set, every vertex is also recorded here in the order the pmx receives it. Set by the headless
    /// exporter before an export and cleared after; null in normal use, which costs one comparison per
    /// vertex. This exists because comparing the pmx against the live mesh has to be done vertex by vertex,
    /// and a mesh read at a different moment than the write - while the viewer's model is animating - is
    /// not the same vertex list at all.
    /// </summary>
    public static string VertexDumpPath;

    private static readonly List<string> _writtenVertices = new List<string>();

    private static void RecordVertex(Vertex vertex, string rendererName)
    {
        var extra = vertex.ExtraUvCoordinate;
        var parts = new List<string>(24)
        {
            vertex.Coordinate.x.ToString("R"), vertex.Coordinate.y.ToString("R"), vertex.Coordinate.z.ToString("R"),
            vertex.Normal.x.ToString("R"), vertex.Normal.y.ToString("R"), vertex.Normal.z.ToString("R"),
            vertex.UvCoordinate.x.ToString("R"), vertex.UvCoordinate.y.ToString("R"),
        };
        for (int i = 0; i < 3; i++)
        {
            var layer = extra != null && i < extra.Length ? extra[i] : Vector4.zero;
            parts.Add(layer.x.ToString("R"));
            parts.Add(layer.y.ToString("R"));
            parts.Add(layer.z.ToString("R"));
            parts.Add(layer.w.ToString("R"));
        }
        parts.Add(rendererName);
        _writtenVertices.Add(string.Join(" ", parts));
    }

    private static void FlushVertexDump()
    {
        if (VertexDumpPath == null) return;
        File.WriteAllLines(VertexDumpPath, _writtenVertices);
        Debug.Log($"[ModelExporter] wrote {_writtenVertices.Count} written vertices to {VertexDumpPath}");
        _writtenVertices.Clear();
        VertexDumpPath = null;
    }

    private static int GetBoneIndex(List<Transform> bones, Transform bone)
    {
        return bones.Contains(bone) ? bones.IndexOf(bone) : 0;
    }

    /// <summary>
    /// The head bone, whose space the game's facial shadow is measured in: the viewer sets
    /// `_faceShadowHeadMat` from it every frame (`HeadBone.transform.worldToLocalMatrix`) and the vertex
    /// program transforms each vertex by it, so the pixel program can read the vertex's height inside the
    /// head. A static export can carry the same number computed at the rest pose.
    /// </summary>
    private static Transform FindHeadBone(List<Transform> bones)
    {
        foreach (var bone in bones)
        {
            if (bone != null && bone.name == "Head") return bone;
        }
        return null;
    }

    /// <summary> Credit to pohype: https://discussions.unity.com/t/reading-meshes-at-runtime-that-are-not-enabled-for-read-write/804189/7 </summary>
    public static Mesh MakeReadableMeshCopy(Mesh nonReadableMesh)
    {
        Mesh meshCopy = new Mesh();
        meshCopy.indexFormat = nonReadableMesh.indexFormat;

        // Handle vertices
        GraphicsBuffer verticesBuffer = nonReadableMesh.GetVertexBuffer(0);
        int totalSize = verticesBuffer.stride * verticesBuffer.count;
        byte[] data = new byte[totalSize];
        verticesBuffer.GetData(data);
        meshCopy.SetVertexBufferParams(nonReadableMesh.vertexCount, nonReadableMesh.GetVertexAttributes());
        meshCopy.SetVertexBufferData(data, 0, 0, totalSize);
        verticesBuffer.Release();

        // Handle triangles
        meshCopy.subMeshCount = nonReadableMesh.subMeshCount;
        GraphicsBuffer indexesBuffer = nonReadableMesh.GetIndexBuffer();
        int tot = indexesBuffer.stride * indexesBuffer.count;
        byte[] indexesData = new byte[tot];
        indexesBuffer.GetData(indexesData);
        meshCopy.SetIndexBufferParams(indexesBuffer.count, nonReadableMesh.indexFormat);
        meshCopy.SetIndexBufferData(indexesData, 0, 0, tot);
        indexesBuffer.Release();

        // Restore submesh structure
        uint currentIndexOffset = 0;
        for (int i = 0; i < meshCopy.subMeshCount; i++)
        {
            uint subMeshIndexCount = nonReadableMesh.GetIndexCount(i);
            meshCopy.SetSubMesh(i, new SubMeshDescriptor((int)currentIndexOffset, (int)subMeshIndexCount));
            currentIndexOffset += subMeshIndexCount;
        }

        // Recalculate normals and bounds
        meshCopy.RecalculateNormals();
        meshCopy.RecalculateBounds();

        return meshCopy;
    }
